def library(root):
    """<root>/digits/ with a thermo library and a kinetics library of REACTIONS."""
    folder = os.path.join(root, "digits")
    for name in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, name))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write(thermo_library_text(LABELS))
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label in LABELS:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(REACTIONS.items()):
            handle.write(f'entry(index={index}, label="{label}", degeneracy=1.0, kinetics={kinetics}, '
                         f'shortDesc="""The chemkin file reaction is {label}""")\n')
    return thermo_path, kinetics_path


def name(label):
    """A species name of the export without RMG's index (older downloads): AR(7) -> AR."""
    return re.sub(r"\(\d+\)$", "", label)


def key(reactants, products):
    """The reaction's species, either way round, from Cantera's species -> coefficient mappings."""
    def side(species):
        return tuple(sorted(name(label) for label, count in species.items() for _ in range(int(count))))
    return frozenset([side(reactants), side(products)])


def label_key(label):
    """key() of a library label, as "HCCO + O <=> CO + CO + H"."""
    def counts(side):
        found = {}
        for label in side.split(" + "):
            found[label] = found.get(label, 0) + 1
        return found
    reactants, products = label.split(" <=> ")
    return key(counts(reactants), counts(products))


def si(value, units, order=None):
    """A stored value in Cantera's units (kmol, m, s, J/kmol); order for rate constants."""
    value_si = ScalarQuantity(value, units).value_si
    return value_si * 1000 ** (order - 1) if order else value_si * 1000


ORDERS = {"s^-1": 1, BI: 2, TER: 3}


def stored_arrhenius(rate):
    return [si(rate.a, rate.a_units, ORDERS[rate.a_units]), rate.n, si(rate.e, rate.e_units)]


def stored_values(data, efficiencies, kinetics):
    """The numbers of one database rate, as Cantera has them, for each Cantera reaction it gives."""
    kind = data.type
    if kind == "arrhenius":
        return [stored_arrhenius(data)]
    if kind == "multi_arrhenius":
        return [stored_arrhenius(rate) for rate in data.arrhenius_set]
    if kind == "third_body":
        return [[*stored_arrhenius(data.low_arrhenius), efficiencies]]
    if kind in ("lindemann", "troe"):
        values = [*stored_arrhenius(data.low_arrhenius), *stored_arrhenius(data.high_arrhenius), efficiencies]
        if kind == "troe":
            values += [data.alpha, data.t3, data.t1, data.t2]
        return [values]
    if kind == "pdep_arrhenius":
        return [[value for point in data.pressure_set for value in (point.pressure, *stored_arrhenius(point.arrhenius))]]
    if kind == "multi_pdep_arrhenius":
        return [stored_values(pdep, efficiencies, kinetics)[0] for pdep in data.pdep_arrhenius_set]
    if kind == "chebyshev":
        order = ORDERS[data.units]
        coeffs = [list(row) for row in data.coefficient_matrix]
        coeffs[0][0] += math.log10(1e-3 ** (order - 1))
        return [[kinetics.min_temp, kinetics.max_temp, kinetics.min_pressure, kinetics.max_pressure,
                 *[value for row in coeffs for value in row]]]
    raise ValueError(kind)


def cantera_arrhenius(rate):
    return [rate.pre_exponential_factor, rate.temperature_exponent, rate.activation_energy]


def cantera_values(reaction):
    """The numbers of a Cantera reaction, in the order of stored_values."""
    import cantera as ct
    rate = reaction.rate
    efficiencies = {name(species): value for species, value in reaction.third_body.efficiencies.items()} \
        if reaction.third_body is not None else {}
    if isinstance(rate, (ct.TroeRate, ct.LindemannRate)):
        values = [*cantera_arrhenius(rate.low_rate), *cantera_arrhenius(rate.high_rate), efficiencies]
        if isinstance(rate, ct.TroeRate):
            values += list(rate.falloff_coeffs) + [0.0] * (4 - len(rate.falloff_coeffs))
        return values
    if isinstance(rate, ct.PlogRate):
        return [value for pressure, arrhenius in rate.rates for value in (pressure, *cantera_arrhenius(arrhenius))]
    if isinstance(rate, ct.ChebyshevRate):
        return [*rate.temperature_range, *rate.pressure_range, *rate.data.flatten()]
    if reaction.reaction_type.startswith("three-body"):
        return [*cantera_arrhenius(rate), efficiencies]
    return cantera_arrhenius(rate)


def differences(expected, actual):
    """The largest relative difference of two lists of numbers (and efficiency mappings)."""
    largest = 0.0
    if len(expected) != len(actual):
        return math.inf
    for want, got in zip(expected, actual):
        if isinstance(want, dict):
            if set(want) != set(got):
                return math.inf
            pairs = [(want[k], got[k]) for k in want]
        else:
            pairs = [(want, got)]
        for a, b in pairs:
            largest = max(largest, 0.0 if a == b else abs(a - b) / max(abs(a), abs(b)))
    return largest


class StoredNumberTests(SimpleTestCase):
    def test_more_digits_only_where_rmg_rounds(self):
        cases = [
            (5836.0, ".3g", "5836"), (8552.0, ".3g", "8552"), (91.0, ".3g", "91"), (9999000000.0, ".3g", "9.999e+09"),
            (0.562, ".3e", "5.620e-01"), (0.10896, ".3e", "1.0896e-01"), (1.0e13, ".3e", "1.000e+13"),
            (0.002, ".2f", "0.002"), (0.375, ".2f", "0.375"), (6.0, ".2f", "6.00"),
            (-0.0004, ".3f", "-0.0004"), (0.0, ".3f", "0.000"), (1.0, ".6f", "1.000000"),
            # Ea of 31736.3 cal/mol in kcal/mol, with RMG's arithmetic noise.
            (31.736300000000004, ".3f", "31.7363"),
            # 98.6923 atm stored in Pa and divided back.
            (98.69229999999999, ".3f", "98.6923"),
        ]
        for value, spec, text in cases:
            with self.subTest(value=value, spec=spec):
                self.assertEqual(exports._stored_number(value, spec), text)

    def test_a_value_without_a_short_decimal_gets_the_digits_of_a_double(self):
        value = 50000 / 4184
        text = exports._stored_number(value, ".3f")
        self.assertLessEqual(abs(float(text) - value), 8 * math.ulp(value))
        self.assertGreater(len(text), 15)


class ExportDigitsTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        directory = tempfile.mkdtemp()
        try:
            cls.model = db.KineticModel.objects.create(model_name="digits")
            thermo_path, kinetics_path = library(directory)
            import_thermo(thermo_path, cls.model, MODELS)
            cls.counts = import_kinetics(kinetics_path, cls.model, MODELS)
        finally:
            shutil.rmtree(directory)

    def stored(self):
        """Fixture label -> the stored numbers of its rate, one list per Cantera reaction."""
        names = dict(db.SpeciesName.objects.filter(kinetic_model=self.model).values_list("species_id", "name"))
        stored = {}
        for comment in db.KineticsComment.objects.filter(kinetic_model=self.model).select_related("kinetics"):
            kinetics = comment.kinetics
            efficiencies = {names[e.species_id]: e.efficiency for e in kinetics.efficiency_set.all()}
            label = comment.comment[len("The chemkin file reaction is "):]
            stored[label] = stored_values(kinetics.data, efficiencies, kinetics)
        return stored

    def solution(self):
        import cantera as ct
        return ct.Solution(yaml=exports.build_cantera_yaml(self.model).content.decode())

    def compare(self, solution):
        """Fixture label -> the largest relative difference of its Cantera reactions from the database."""
        reactions = {}
        for reaction in solution.reactions():
            reactions.setdefault(key(reaction.reactants, reaction.products), []).append(cantera_values(reaction))
        found = {}
        for label, values in self.stored().items():
            got = list(reactions.get(label_key(label), []))
            if len(got) != len(values):
                found[label] = math.inf
                continue
            # The duplicates of one rate in either order: each with its closest Cantera reaction.
            largest = 0.0
            for want in values:
                closest = min(got, key=lambda candidate: differences(want, candidate))
                largest = max(largest, differences(want, closest))
                got.remove(closest)
            found[label] = largest
        return found

    def test_every_rate_is_imported(self):
        self.assertEqual((self.counts["imported"], self.counts["failed"]), (len(REACTIONS), 0))

    def test_cantera_file_has_the_stored_values(self):
        found = self.compare(self.solution())
        self.assertEqual(set(found), set(REACTIONS))
        for label, difference in found.items():
            with self.subTest(label):
                self.assertLess(difference, 1e-14)

    def test_rmgs_digits_alone_change_these_values(self):
        """Without the rewrite, each rate but the last differs from the database: the fixture has
        values that RMG rounds."""
        with mock.patch.object(exports, "_write_stored_digits", lambda text, *args: text):
            found = self.compare(self.solution())
        for label, difference in found.items():
            with self.subTest(label):
                if label == EXACT:
                    self.assertLess(difference, 1e-14)
                else:
                    self.assertGreater(difference, 1e-5)

    def rmg_file(self):
        """The CHEMKIN text RMG writes for the model, with its reactions and species."""
        from rmgpy.chemkin import save_chemkin_file
        from rmgpy.reaction import Reaction
        from rmgpy.species import Species
        from rmgpy.thermo import NASA, NASAPolynomial
        from rmgpy.transport import TransportData

        species_map, _ = exports._build_rmg_species_map(self.model, NASAPolynomial, NASA, TransportData, Species)
        species = list(species_map.values())
        reactions = exports._build_rmg_reactions(self.model, species_map, Reaction)
        with tempfile.TemporaryDirectory() as directory:
            path = os.path.join(directory, "chem.inp")
            save_chemkin_file(path, species, reactions, verbose=False, check_for_duplicates=False)
            with open(path) as handle:
                return handle.read(), reactions, species

    def test_entries_are_rmgs_at_rmgs_digits(self):
        from rmgpy.chemkin import write_kinetics_entry
        _, reactions, species = self.rmg_file()
        for reaction in reactions:
            with self.subTest(str(reaction)):
                parts = exports._kinetics_entry_parts(reaction, species)
                self.assertEqual(exports._render_entry(parts, format),
                                 write_kinetics_entry(reaction, species_list=species, verbose=False))

    def test_only_the_rounded_numbers_change(self):
        text, reactions, species = self.rmg_file()
        with self.assertNoLogs("database.services.exports", logging.WARNING):
            rewritten = exports._write_stored_digits(text, reactions, species)
        old_lines, new_lines = text.splitlines(), rewritten.splitlines()
        self.assertEqual(len(old_lines), len(new_lines))
        changed = [(old, new) for old, new in zip(old_lines, new_lines) if old != new]
        self.assertTrue(changed)
        for old, new in changed:
            old_tokens, new_tokens = re.split(r"[\s/]+", old.strip()), re.split(r"[\s/]+", new.strip())
            self.assertEqual(len(old_tokens), len(new_tokens), (old, new))
            for old_token, new_token in zip(old_tokens, new_tokens):
                if old_token != new_token:
                    # A number of RMG's, rounded from the new one.
                    self.assertAlmostEqual(float(old_token), float(new_token), delta=6e-3 * max(1, abs(float(new_token))))
        self.assertIn("TROE/ 5.620e-01 91        5836      8552     /", rewritten)
        self.assertIn("TROE/ 5.620e-01 91        5.84e+03  8.55e+03 /", text)
        self.assertRegex(rewritten, r"O2(?:\(\d+\))?/0.002/")
        self.assertRegex(rewritten, r"AR(?:\(\d+\))?/0.375/")
        self.assertIn("PLOG/ 0.0001316", rewritten)
        self.assertIn(" 1.2717e+01 ", rewritten)
        exact = [line for line in new_lines if re.match(r"CH2CO(?:\(\d+\))?\+O(?:\(\d+\))?<=>", line)]
        self.assertEqual(len(exact), 1)
        self.assertIn(exact[0], old_lines)

    def test_duplicates_are_still_declared(self):
        text = [v.decode() for k, v in exports._generate_chemkin_files(self.model).items() if k.endswith("_chem.inp")][0]
        # Two MultiArrhenius rates and two duplicate PLOG rates.
        self.assertEqual(text.count("DUPLICATE"), 4)
        solution = self.solution()
        duplicates = [r for r in solution.reactions() if r.duplicate]
        self.assertEqual(len(duplicates), 4)

    def test_an_entry_it_does_not_rebuild_keeps_rmgs_digits(self):
        text, reactions, species = self.rmg_file()
        from rmgpy.kinetics import Troe
        parts = exports._kinetics_entry_parts

        def no_troe(reaction, species_list):
            return None if isinstance(reaction.kinetics, Troe) else parts(reaction, species_list)

        with mock.patch.object(exports, "_kinetics_entry_parts", no_troe), \
                self.assertLogs("database.services.exports", logging.WARNING) as logs:
            rewritten = exports._write_stored_digits(text, reactions, species)
        self.assertIn("1 reaction(s) keep the digits", logs.output[0])
        self.assertIn("TROE/ 5.620e-01 91        5.84e+03  8.55e+03 /", rewritten)
        self.assertIn("PLOG/ 0.0001316", rewritten)

    def test_a_file_laid_out_otherwise_is_not_changed(self):
        text, reactions, species = self.rmg_file()
        changed = text.replace("REACTIONS    KCAL/MOLE   MOLES\n\n", "REACTIONS    KCAL/MOLE   MOLES\n\n\n")
        with self.assertLogs("database.services.exports", logging.WARNING):
            self.assertEqual(exports._write_stored_digits(changed, reactions, species), changed)
        reversed_reactions = list(reversed(reactions))
        with self.assertLogs("database.services.exports", logging.WARNING):
            self.assertEqual(exports._write_stored_digits(text, reversed_reactions, species), text)
