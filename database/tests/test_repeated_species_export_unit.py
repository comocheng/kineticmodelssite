def library(root):
    """<root>/bohon/ with a thermo library and a kinetics library of REACTIONS."""
    folder = os.path.join(root, "bohon")
    for name in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, name))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\n')
        for index, label in enumerate(ADJ):
            handle.write(f'entry(index={index}, label="{label}", molecule="""\n{ADJ[label]}\n""", '
                         f'thermo={NASA_TEXT}, shortDesc="""test""", longDesc="""""")\n')
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label, adjacency in ADJ.items():
            handle.write(f"{label}\n{adjacency}\n\n")
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(REACTIONS.items()):
            duplicate = "duplicate = True," if label.startswith("HO2 + HO2") else ""
            handle.write(f'entry(index={index}, label="{label}", degeneracy=1.0, {duplicate} '
                         f'kinetics={kinetics}, shortDesc="""test""")\n')
    return thermo_path, kinetics_path


def sides(equation):
    """The species of each side, sorted and without RMG's index, from a CHEMKIN or a Cantera
    equation: H2(2)+H(1)+H(1)<=>H2(2)+H2(2) and 2 H(1) + H2(2) <=> H2(2) + H2(2) both give
    (('H', 'H', 'H2'), ('H2', 'H2'))."""
    def side(text):
        species = []
        for term in text.replace("(+M)", "+(M)").split("+"):
            count, _, name = term.strip().rpartition(" ")
            species += [name] * int(count or 1)
        return tuple(sorted(species))

    left, right = re.split(r"<=>|=>|=", re.sub(r"\(\d+\)", "", equation))
    return side(left), side(right)


class RepeatedSpeciesExportTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        directory = tempfile.mkdtemp()
        try:
            cls.model = db.KineticModel.objects.create(model_name="bohon")
            thermo_path, kinetics_path = library(directory)
            import_thermo(thermo_path, cls.model, MODELS)
            cls.counts = import_kinetics(kinetics_path, cls.model, MODELS)
        finally:
            shutil.rmtree(directory)

    def kinetics(self, *species):
        """The model's rate record of the reaction with these species, coefficients included."""
        names = dict(db.SpeciesName.objects.filter(kinetic_model=self.model).values_list("species_id", "name"))
        for kinetics in db.Kinetics.objects.filter(kineticscomment__kinetic_model=self.model):
            stoichiometry = sorted((s.coeff, names[s.species_id]) for s in kinetics.reaction.stoichiometry_set.all())
            if stoichiometry == sorted(species):
                return kinetics
        raise AssertionError(f"no rate record for {species}")

    def chemkin_reactions(self, strict=False):
        """(sides, DUPLICATE or not) of each reaction of the CHEMKIN export."""
        files = exports._generate_chemkin_files(self.model, strict=strict)
        (text,) = [v.decode() for k, v in files.items() if k.endswith("_chem.inp")]
        blocks = re.split(r"^(?=[^!\s]\S*=)", text.split("REACTIONS", 1)[1], flags=re.M)[1:]
        return [(sides(block.split()[0]), "DUPLICATE" in block) for block in blocks]

    def test_import_keeps_the_coefficients(self):
        self.assertEqual((self.counts["imported"], self.counts["failed"]), (5, 0))
        self.kinetics((-1, "H2O2"), (2, "OH"))
        self.kinetics((-2, "HO2"), (1, "H2O2"), (1, "O2"))
        self.kinetics((-2, "H"), (1, "H2"))
        self.kinetics((-2, "H"), (-1, "H2"), (2, "H2"))

    def test_rmg_reaction_repeats_the_species(self):
        reaction = self.kinetics((-1, "H2O2"), (2, "OH")).to_rmg()
        self.assertEqual((len(reaction.reactants), len(reaction.products)), (1, 2))
        self.assertTrue(reaction.is_balanced())
        reaction = self.kinetics((-2, "H"), (-1, "H2"), (2, "H2")).to_rmg()
        self.assertEqual((len(reaction.reactants), len(reaction.products)), (3, 2))
        self.assertTrue(reaction.is_balanced())
        # The CHEMKIN block of the kinetics page.
        text = self.kinetics((-2, "HO2"), (1, "H2O2"), (1, "O2")).to_chemkin()
        self.assertEqual(sides(text.split()[0]), sides("2 HO2 <=> H2O2 + O2"))

    def test_chemkin_export_keeps_every_reaction(self):
        reactions = self.chemkin_reactions()
        self.assertCountEqual([equation for equation, _ in reactions], map(sides, EXPORTED))
        # Only the two HO2 + HO2 rates are duplicates: H + H + H2 is not one of H + H + M.
        duplicates = [equation for equation, duplicate in reactions if duplicate]
        self.assertEqual(duplicates, [sides("2 HO2 <=> H2O2 + O2")] * 2)

    def test_strict_export_does_not_call_them_unbalanced(self):
        reactions = self.chemkin_reactions(strict=True)
        self.assertCountEqual([equation for equation, _ in reactions], map(sides, EXPORTED))

    def test_cantera_file_keeps_every_reaction(self):
        import cantera as ct
        content = exports.build_cantera_yaml(self.model).content.decode()
        solution = ct.Solution(yaml=content)
        self.assertCountEqual([sides(r.equation) for r in solution.reactions()], map(sides, EXPORTED))
        rates = {}
        for reaction in solution.reactions():
            rate = reaction.rate
            arrhenius = [rate.high_rate, rate.low_rate] if hasattr(rate, "high_rate") else [rate]
            rates.setdefault(sides(reaction.equation), []).extend(a.pre_exponential_factor for a in arrhenius)
        for equation, expected in CANTERA_A.items():
            values = sorted(rates[sides(equation)])
            self.assertEqual(len(values), len(expected), equation)
            for value, target in zip(values, sorted(expected)):
                self.assertAlmostEqual(value / target, 1, places=6, msg=equation)
