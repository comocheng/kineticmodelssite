def molecule(label):
    adjacency = ADJ[SAME_AS.get(label, label)].replace("molecularTermSymbol A^2S+\n", "")
    return Molecule().from_adjacency_list(adjacency)


def resonance_forms(label):
    species = RMGSpecies(molecule=[molecule(label)])
    species.generate_resonance_structures()
    return species.molecule


class TolerantThermoLibraryTests(SimpleTestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)

    def load(self, labels, declared_states=None):
        path = os.path.join(self.directory, "ThermoLibrary.py")
        with open(path, "w") as handle:
            handle.write(thermo_library_text(labels))
        library = TolerantThermoLibrary(label="test")
        library.declared_states = declared_states
        library.load(path, local_context=dict(THERMO_CONTEXT))
        return library

    def test_term_symbol_keeps_excited_and_ground_state_apart(self):
        library = self.load(["OH*", "OH", "OHV", "CO", "CO"])
        self.assertEqual(list(library.entries), ["OH*", "OH", "CO"])
        self.assertEqual(library.states, {"OH*": "A^2S+", "OH": "", "CO": ""})
        skipped = {(s["label"], s["kept"]) for s in library.skipped}
        self.assertEqual(skipped, {("OHV", "OH"), ("CO", "CO")})
        ohv = next(s for s in library.skipped if s["label"] == "OHV")
        self.assertEqual(ohv["reason"], "same structure, multiplicity and electronic state as OH")

    def test_declared_state_keeps_an_entry_without_term_symbol(self):
        library = self.load(["OHX", "OH"], declared_states={"OHX": "excited"})
        self.assertEqual(list(library.entries), ["OHX", "OH"])
        self.assertEqual(library.states["OHX"], "excited")
        self.assertEqual(library.skipped, [])

    def test_undeclared_excited_entry_is_a_reported_duplicate(self):
        library = self.load(["OHX", "OH"])
        self.assertEqual(list(library.entries), ["OHX"])
        self.assertEqual([(s["label"], s["kept"]) for s in library.skipped], [("OH", "OHX")])

    def test_smiles_txt_states(self):
        with open(os.path.join(self.directory, "SMILES.txt"), "w") as handle:
            handle.write("OH\t[OH]\nOHX\texcited[OH]\t! Confirmed by someone\n"
                         "! Deleted by someone: CH*\texcited[CH]\nCH\t[CH]\n")
        self.assertEqual(smiles_txt_states(self.directory), {"OHX": "excited"})

    def test_species_key_and_hash_carry_the_state(self):
        self.assertEqual(species_key(["KEY-2"], "excited"), "KEY-2@excited")
        self.assertEqual(species_key(["KEY-2"]), "KEY-2")
        isomers = [SimpleNamespace(id=7)]
        self.assertNotEqual(get_species_hash(isomers, "excited"), get_species_hash(isomers))


def excited_pair_library(directory, excited, reactions=None):
    """A kinetics library with H + O2 <=> O + OH next to the same reaction of an excited OH.
    `excited` is OH* (term symbol in the dictionary) or OHV (ground-state adjacency list)."""
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label in ("H", "O2", "O", "OH", excited):
            handle.write(f"{label}\n{ADJ[SAME_AS.get(label, label)]}\n\n")
    reactions = reactions or [("OH", "1.04e+14"), (excited, "1.0e+10")]
    with open(os.path.join(directory, "reactions.py"), "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (product, a) in enumerate(reactions):
            handle.write(f'''entry(
    index = {index},
    label = "H + O2 <=> O + {product}",
    degeneracy = 1.0,
    kinetics = Arrhenius(A=({a},'cm^3/(mol*s)'), n=0, Ea=(15286,'cal/mol'), T0=(1,'K')),
    shortDesc = """test""",
)

''')
    return os.path.join(directory, "reactions.py")


class TolerantKineticsLibraryTests(SimpleTestCase):
    """RMG merges isomorphic reactions into one; a reaction of an excited state is not
    isomorphic to the ground state's, though RMG's molecules cannot tell them apart."""

    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)

    def load(self, excited, declared_states=None, reactions=None):
        library = TolerantKineticsLibrary(label="test")
        library.declared_states = declared_states
        library.load(excited_pair_library(self.directory, excited, reactions),
                     local_context=importer.kinetics_local_context())
        return library

    def rates(self, library):
        return {entry.label: type(entry.data).__name__ for entry in library.entries.values()}

    def test_term_symbol_keeps_the_excited_reaction(self):
        self.assertEqual(self.rates(self.load("OH*")),
                         {"H + O2 <=> O + OH": "Arrhenius", "H + O2 <=> O + OH*": "Arrhenius"})

    def test_declared_state_keeps_the_excited_reaction(self):
        library = self.load("OHV", declared_states={"OHV": "excited"})
        self.assertEqual(self.rates(library),
                         {"H + O2 <=> O + OH": "Arrhenius", "H + O2 <=> O + OHV": "Arrhenius"})
        self.assertFalse(any(entry.item.duplicate for entry in library.entries.values()))

    def test_undeclared_excited_label_is_merged_as_rmg_does(self):
        self.assertEqual(self.rates(self.load("OHV")), {"H + O2 <=> O + OH": "MultiArrhenius"})

    def test_true_duplicates_are_still_merged(self):
        library = self.load("OH*", reactions=[("OH", "1.04e+14"), ("OH", "2.0e+13"), ("OH*", "1.0e+10")])
        self.assertEqual(self.rates(library),
                         {"H + O2 <=> O + OH": "MultiArrhenius", "H + O2 <=> O + OH*": "Arrhenius"})

    def test_an_unbalanced_reaction_is_skipped_not_the_library(self):
        # RMG 4 refuses the whole library for one unbalanced reaction (PCI2017/036-Rashidi).
        library = self.load("OH*", reactions=[("OH", "1.04e+14"), ("O2", "1.0e+10")])
        self.assertEqual(self.rates(library), {"H + O2 <=> O + OH": "Arrhenius"})
        self.assertEqual(library.rejected, [("H + O2 <=> O + O2", "not balanced")])

    def test_activation_energy_in_joules_per_mole(self):
        # CHEMKIN files in JOULES/MOLE (Chernov, CombFlame2017/45-Olm) give Ea in J/mol.
        rate = kd.Arrhenius(type="arrhenius", a=1e13, a_si=1e7, a_units="cm^3/(mol*s)", n=0,
                                     e=67481.1, e_si=67481.1, e_units="J/mol")
        self.assertAlmostEqual(rate.to_rmg().Ea.value_si, 67481.1)
        with self.assertRaises(ValueError):
            kd.Arrhenius(type="arrhenius", a=1e13, a_si=1e7, a_units="cm^3/(mol*s)", n=0,
                                  e=1, e_si=1, e_units="J")


class SpeciesIdentityTests(TestCase):
    def setUp(self):
        self.model = db.KineticModel.objects.create(model_name="test model")

    def names(self, species=None):
        rows = db.SpeciesName.objects.filter(kinetic_model=self.model)
        if species is not None:
            rows = rows.filter(species=species)
        return sorted(rows.values_list("name", flat=True))

    def test_one_resonance_form_and_all_forms_share_one_record(self):
        forms = resonance_forms("HCCO")
        self.assertGreater(len(forms), 1)
        from_thermo = get_or_create_species(self.model, "HCCO", [molecule("HCCO")], MODELS)
        from_reaction = get_or_create_species(self.model, "HCCO", forms, MODELS)
        self.assertEqual(from_thermo.pk, from_reaction.pk)
        self.assertEqual(from_reaction.isomers.count(), len(forms))
        self.assertEqual(db.Species.objects.count(), 1)
        self.assertEqual(self.names(), ["HCCO"])

    def test_resonance_forms_first_then_one_form(self):
        first = get_or_create_species(self.model, "HCCO", resonance_forms("HCCO"), MODELS)
        second = get_or_create_species(None, "ketenyl", [molecule("HCCO")], MODELS)
        self.assertEqual(first.pk, second.pk)

    def test_resonance_forms_with_different_keys_share_one_record(self):
        for label in ("CH2COOH", "H2NCO"):
            with self.subTest(label):
                forms = resonance_forms(label)
                self.assertGreater(len({importer.molecule_key(form) for form in forms}), 1)
                from_thermo = get_or_create_species(self.model, label, [molecule(label)], MODELS)
                from_reaction = get_or_create_species(self.model, label, forms, MODELS)
                self.assertEqual(from_thermo.pk, from_reaction.pk)
                self.assertEqual(from_reaction.isomers.count(), len(forms))
                # Another model's thermo entry may be written as a different form.
                for form in forms:
                    self.assertEqual(get_or_create_species(None, "", [form], MODELS).pk,
                                     from_reaction.pk)
                formula = forms[0].get_formula()
                self.assertEqual(
                    db.Species.objects.filter(isomers__formula__formula=formula).distinct().count(), 1)
                self.assertEqual(self.names(from_reaction), [label])

    def test_all_forms_with_different_keys_first_then_one_form(self):
        forms = resonance_forms("CH2COOH")
        first = get_or_create_species(self.model, "CH2COOH", forms, MODELS)
        for form in forms:
            self.assertEqual(get_or_create_species(self.model, "CH2COOH", [form], MODELS).pk, first.pk)
        self.assertEqual(db.Species.objects.count(), 1)

    def test_spin_states_stay_apart(self):
        triplet = Molecule().from_adjacency_list(
            "multiplicity 3\n1 C u2 p0 c0 {2,S} {3,S}\n2 H u0 p0 c0 {1,S}\n3 H u0 p0 c0 {1,S}")
        singlet = Molecule().from_adjacency_list(
            "multiplicity 1\n1 C u0 p1 c0 {2,S} {3,S}\n2 H u0 p0 c0 {1,S}\n3 H u0 p0 c0 {1,S}")
        a = get_or_create_species(self.model, "CH2", [triplet], MODELS)
        b = get_or_create_species(self.model, "CH2(S)", [singlet], MODELS)
        self.assertNotEqual(a.pk, b.pk)

    def test_excited_state_is_its_own_record(self):
        ground = get_or_create_species(self.model, "OH", [molecule("OH")], MODELS)
        excited = get_or_create_species(self.model, "OH*", [molecule("OH")], MODELS,
                                        electronic_state="A^2S+")
        again = get_or_create_species(None, "", [molecule("OH")], MODELS, electronic_state="A^2S+")
        self.assertNotEqual(ground.pk, excited.pk)
        self.assertEqual(excited.pk, again.pk)
        self.assertEqual((ground.electronic_state, excited.electronic_state), ("", "A^2S+"))
        self.assertEqual(set(ground.isomers.all()), set(excited.isomers.all()))
        excited.refresh_from_db()
        ground.refresh_from_db()
        self.assertNotEqual(ground.hash, excited.hash)
        self.assertEqual(self.names(ground), ["OH"])
        self.assertEqual(self.names(excited), ["OH*"])
        # An InChIKey is a ground state.
        self.assertEqual(set(inchikey_species_map().values()), {ground.pk})

    def test_existing_split_records_are_reused_not_multiplied(self):
        # Records an older import left behind: one resonance form, and the whole set.
        forms = resonance_forms("HCCO")
        one = get_or_create_species(None, "", forms[:1], MODELS)
        isomers = list(one.isomers.all())
        get_or_create_species(None, "", forms, MODELS)
        db.Species.objects.all().delete()
        single = db.Species.objects.create(hash=get_species_hash(isomers))
        single.isomers.add(*isomers)
        full_isomers = list(db.Isomer.objects.filter(formula__formula="C2HO"))
        full = db.Species.objects.create(hash="placeholder")
        full.isomers.add(*full_isomers)
        found = get_or_create_species(self.model, "HCCO", [molecule("HCCO")], MODELS)
        self.assertEqual(found.pk, full.pk)
        self.assertEqual(db.Species.objects.count(), 2)

    def test_reaction_placeholder_is_replaced_by_the_name(self):
        species = get_or_create_species(self.model, "", [molecule("OH")], MODELS)
        get_or_create_species(self.model, "OH", [molecule("OH")], MODELS)
        get_or_create_species(self.model, "", [molecule("OH")], MODELS)
        self.assertEqual(self.names(species), ["OH"])

    def test_no_placeholder_next_to_a_name_left_by_an_older_import(self):
        species = get_or_create_species(self.model, "OH", [molecule("OH")], MODELS)
        db.SpeciesName.objects.create(species=species, kinetic_model=self.model, name="")
        get_or_create_species(self.model, "OH", [molecule("OH")], MODELS)
        self.assertEqual(self.names(species), ["OH"])

    def test_two_ground_state_names_for_one_structure_are_both_kept(self):
        species = get_or_create_species(self.model, "OH", [molecule("OH")], MODELS)
        get_or_create_species(self.model, "HYDROXYL", [molecule("OH")], MODELS)
        self.assertEqual(self.names(species), ["HYDROXYL", "OH"])

    def test_historical_models_keep_the_isomer_set_identity(self):
        legacy = SimpleNamespace(**vars(MODELS))
        legacy.Structure = SimpleNamespace(_meta=SimpleNamespace(get_fields=lambda: []))
        legacy.Species = SimpleNamespace(objects=db.Species.objects,
                                         _meta=SimpleNamespace(get_fields=lambda: []))
        forms = resonance_forms("HCCO")
        one = get_or_create_species(None, "", forms[:1], MODELS)
        isomers = list(one.isomers.all())
        other = species_record(isomers + [isomers[0]], forms[:1], legacy, electronic_state="excited")
        self.assertEqual(other.pk, one.pk)
        self.assertEqual(other.hash, get_species_hash(isomers))


class LibraryImportTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model = db.KineticModel.objects.create(model_name="test model")
        self.thermo_path, self.kinetics_path = model_folder(
            self.directory, "model", ["H", "O", "O2", "OH*", "OH", "H2O", "HCCO", "CO", "AR"],
            kinetics=True)

    def record(self, name, model=None):
        return db.Species.objects.get(speciesname__kinetic_model=model or self.model,
                                      speciesname__name=name)

    def test_thermo_import_keeps_ground_and_excited_state(self):
        counts = import_thermo(self.thermo_path, self.model, MODELS)
        self.assertEqual(counts["failed"], 0)
        self.assertEqual(counts["skipped_duplicates"], [])
        self.assertEqual(counts["excited_states"], {"OH*": "A^2S+"})
        self.assertNotEqual(self.record("OH").pk, self.record("OH*").pk)
        self.assertEqual(self.record("OH*").thermo_set.count(), 1)
        self.assertEqual(self.record("OH").thermo_set.count(), 1)

    def test_importing_twice_adds_no_second_thermo_link(self):
        import_thermo(self.thermo_path, self.model, MODELS)
        import_thermo(self.thermo_path, self.model, MODELS)
        links = db.ThermoComment.objects.filter(kinetic_model=self.model)
        self.assertEqual(links.count(), 9)
        self.assertEqual(links.values("thermo").distinct().count(), 9)

