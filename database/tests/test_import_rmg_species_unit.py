def thermo_library_text(labels):
    entries = []
    for index, label in enumerate(labels):
        adjacency = ADJ[SAME_AS.get(label, label)]
        entries.append(f'''entry(
    index = {index},
    label = "{label}",
    molecule =
"""
{adjacency}
""",
    thermo = {NASA_TEXT},
    shortDesc = """test {label}""",
    longDesc = """""",
)
''')
    return 'name = "test"\nshortDesc = ""\nlongDesc = """"""\n' + "\n".join(entries)


