LABELS = ("H", "O", "O2", "OH", "HO2", "H2O")
COEFFS = "[[11.5,0.52,-0.05],[-0.62,0.31,0.021],[-0.21,0.11,0.012],[-0.05,0.02,0.003]]"
CAI = {"H + O2 <=> HO2": (290, 3000), "H + HO2 <=> H2O + O": (290, 3000)}
# Jin: other T ranges, and the same coefficients for both reactions (as Jin's iC3H5OH + H, CH3CHCHOH + H
# and C2H3OH + H), so a link is paired with its entry by its species, not only by its coefficients.
JIN = {"H + O2 <=> HO2": (270, 3000), "H + HO2 <=> H2O + O": (270, 4000)}
ATM = 101325.0


def chebyshev_model(root, name, ranges, pmin=0.00986923, arrhenius_tmin=None):
    """<root>/<name>/ with a thermo library and a kinetics library: one Chebyshev entry per
    label (T range from `ranges`), and an Arrhenius entry with a T range if arrhenius_tmin."""
    folder = os.path.join(root, name)
    for library in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, library))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write(thermo_library_text(LABELS))
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label in LABELS:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    text = 'name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n'
    entries = [(label, f"Chebyshev(coeffs={COEFFS}, kunits='cm^3/(mol*s)', Tmin=({tmin},'K'), Tmax=({tmax},'K'), "
                       f"Pmin=({pmin},'atm'), Pmax=(98.6923,'atm'))") for label, (tmin, tmax) in ranges.items()]
    if arrhenius_tmin is not None:
        entries.append(("O + HO2 <=> OH + O2", "Arrhenius(A=(3.25e+13,'cm^3/(mol*s)'), n=0, Ea=(0,'cal/mol'), "
                                                f"T0=(1,'K'), Tmin=({arrhenius_tmin},'K'), Tmax=(2500,'K'))"))
    for index, (label, kinetics) in enumerate(entries):
        text += f'''
entry(
    index = {index},
    label = "{label}",
    degeneracy = 1.0,
    kinetics = {kinetics},
    shortDesc = """The chemkin file reaction is {label}""",
)
'''
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write(text)
    return thermo_path, kinetics_path


def import_model(root, name, ranges, **options):
    model = db.KineticModel.objects.create(model_name=name)
    thermo_path, kinetics_path = chebyshev_model(root, name, ranges, **options)
    import_thermo(thermo_path, model, MODELS)
    counts = import_kinetics(kinetics_path, model, MODELS)
    return model, kinetics_path, counts


def records(model):
    """'H + O2' style key (the reaction's species names, sorted) -> the model's rate record."""
    names = dict(db.SpeciesName.objects.filter(kinetic_model=model).values_list("species_id", "name"))
    out = {}
    for link in db.KineticsComment.objects.filter(kinetic_model=model).select_related("kinetics"):
        species = db.Stoichiometry.objects.filter(reaction_id=link.kinetics.reaction_id).values_list("species_id", flat=True)
        out[" + ".join(sorted(names[s] for s in species))] = link.kinetics
    return out


O2_RATE, HO2_RATE, ARRHENIUS = "H + HO2 + O2", "H + H2O + HO2 + O", "HO2 + O + O2 + OH"


def t_range(kinetics):
    return (kinetics.min_temp, kinetics.max_temp)


def old_import(model, first):
    """What the importer left before the range was in the identity: the model's Chebyshev links on
    the first model's records of the same reactions (a record no model uses any more is deleted)."""
    for key, kinetics in records(model).items():
        if kinetics.raw_data["type"] != "chebyshev":
            continue
        db.KineticsComment.objects.filter(kinetic_model=model, kinetics=kinetics).update(kinetics=records(first)[key])
        if not db.KineticsComment.objects.filter(kinetics=kinetics).exists():
            kinetics.delete()


class ChebyshevImportTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.cai, *_ = import_model(self.directory, "cai", CAI)

    def test_other_range_gets_its_own_record(self):
        jin, _, counts = import_model(self.directory, "jin", JIN)
        self.assertEqual((counts["imported"], counts["failed"]), (2, 0))
        for key, tmax in ((O2_RATE, 3000), (HO2_RATE, 4000)):
            cai_rate, jin_rate = records(self.cai)[key], records(jin)[key]
            self.assertNotEqual(cai_rate.pk, jin_rate.pk)
            self.assertEqual(cai_rate.raw_data, jin_rate.raw_data)
            self.assertEqual(t_range(cai_rate), (290, 3000))
            self.assertEqual(t_range(jin_rate), (270, tmax))
            self.assertEqual(cai_rate.reaction_id, jin_rate.reaction_id)

    def test_the_same_range_shares_the_record(self):
        zhang, *_ = import_model(self.directory, "zhang", CAI)
        self.assertEqual({k: v.pk for k, v in records(zhang).items()}, {k: v.pk for k, v in records(self.cai).items()})
        self.assertEqual(db.Kinetics.objects.count(), 2)

    def test_other_pressure_range_gets_its_own_record(self):
        other, *_ = import_model(self.directory, "other", CAI, pmin=0.01)
        self.assertNotEqual(records(other)[O2_RATE].pk, records(self.cai)[O2_RATE].pk)
        self.assertAlmostEqual(records(other)[O2_RATE].min_pressure, 0.01 * ATM)
        self.assertAlmostEqual(records(self.cai)[O2_RATE].min_pressure, 0.00986923 * ATM)

    def test_importing_again_finds_the_same_records(self):
        jin, jin_path, _ = import_model(self.directory, "jin", JIN)
        before = sorted(db.KineticsComment.objects.values_list("kinetic_model_id", "kinetics_id"))
        counts = import_kinetics(jin_path, jin, MODELS)
        self.assertEqual((counts["imported"], counts["failed"]), (2, 0))
        self.assertEqual(sorted(db.KineticsComment.objects.values_list("kinetic_model_id", "kinetics_id")), before)
        self.assertEqual(db.Kinetics.objects.count(), 4)

    def test_other_rates_keep_one_record_and_the_first_range(self):
        # A range that only says where the rate holds is not part of the identity, as before.
        first, *_ = import_model(self.directory, "first", {}, arrhenius_tmin=300)
        second, *_ = import_model(self.directory, "second", {}, arrhenius_tmin=400)
        self.assertEqual(records(first)[ARRHENIUS].pk, records(second)[ARRHENIUS].pk)
        self.assertEqual(t_range(records(second)[ARRHENIUS]), (300, 2500))

    def test_each_record_has_its_own_fingerprint(self):
        jin, *_ = import_model(self.directory, "jin", JIN)
        cai_rate, jin_rate = records(self.cai)[O2_RATE], records(jin)[O2_RATE]
        self.assertEqual(jin_rate.rate_fingerprint, kinetics_fingerprint(jin_rate))
        self.assertNotEqual(jin_rate.rate_fingerprint, cai_rate.rate_fingerprint)

    def test_downloads_write_each_models_range(self):
        import cantera as ct
        jin, *_ = import_model(self.directory, "jin", JIN)
        for model, tmins in ((self.cai, {"290.000"}), (jin, {"270.000"})):
            (text,) = [v.decode() for k, v in exports._generate_chemkin_files(model).items() if k.endswith("_chem.inp")]
            self.assertEqual({m.group(1) for m in re.finditer(r"TCHEB/\s*(\S+)", text)}, tmins)
        solution = ct.Solution(yaml=exports.build_cantera_yaml(jin).content.decode())
        ranges = sorted(tuple(r.rate.temperature_range) for r in solution.reactions())
        self.assertEqual(ranges, [(270.0, 3000.0), (270.0, 4000.0)])


class ChebyshevConstraintTests(TestCase):
    def setUp(self):
        h, o2, ho2 = (get_or_create_species(None, "", [molecule(label)], MODELS) for label in ("H", "O2", "HO2"))
        self.reaction = reaction((-1, h), (-1, o2), (1, ho2))
        self.raw = {"type": "chebyshev", "coefficient_matrix": [[11.5, 0.52], [-0.62, 0.31]], "units": "cm^3/(mol*s)"}
        self.range = {"min_temp": 290.0, "max_temp": 3000.0, "min_pressure": 1000.0, "max_pressure": 1e7}
        db.Kinetics.objects.create(reaction=self.reaction, raw_data=self.raw, **self.range)

    def refused(self, **fields):
        with self.assertRaises(IntegrityError), transaction.atomic():
            db.Kinetics.objects.create(reaction=self.reaction, **fields)

    def test_another_range_is_another_record(self):
        db.Kinetics.objects.create(reaction=self.reaction, raw_data=self.raw, **{**self.range, "min_temp": 270.0})
        db.Kinetics.objects.create(reaction=self.reaction, raw_data=self.raw, **{**self.range, "min_pressure": 1013.25})
        self.assertEqual(db.Kinetics.objects.count(), 3)

    def test_the_same_range_is_refused(self):
        self.refused(raw_data=self.raw, **self.range)

    def test_a_chebyshev_record_has_its_range(self):
        self.refused(raw_data=self.raw, **{**self.range, "max_pressure": None})

    def test_other_rates_are_one_record_whatever_the_range(self):
        rate = {"type": "arrhenius", "a": 1e13, "n": 0, "e": 0}
        db.Kinetics.objects.create(reaction=self.reaction, raw_data=rate, min_temp=300.0, max_temp=2500.0)
        self.refused(raw_data=rate, min_temp=400.0, max_temp=2500.0)
        self.refused(raw_data=rate)

    def test_identity(self):
        (kinetics,) = db.Kinetics.objects.all()
        self.assertEqual(kinetics_identity(kinetics, min_temp=270.0)["min_temp"], 270.0)
        self.assertEqual({k: v for k, v in kinetics_identity(kinetics).items() if k in self.range}, self.range)
        self.assertEqual(range_identity({"type": "arrhenius"}, 300.0, 2500.0), {})


class ChebyshevMergeTests(TestCase):
    """A species merge merges two reactions: their Chebyshev rates merge only with the same range."""

    def setUp(self):
        single, full = split_records()
        o = get_or_create_species(None, "", [molecule("O")], MODELS)
        co = get_or_create_species(None, "", [molecule("CO")], MODELS)
        self.raw = {"type": "chebyshev", "coefficient_matrix": [[11.5, 0.52], [-0.62, 0.31]], "units": "cm^3/(mol*s)"}
        self.rows = []
        for name, species in (("a", single), ("b", full)):
            row = reaction((-1, species), (-1, o), (2, co))
            model = db.KineticModel.objects.create(model_name=name)
            self.rows.append((row, model))

    def rate(self, index, min_temp):
        row, model = self.rows[index]
        kinetics = db.Kinetics.objects.create(reaction=row, raw_data=self.raw, min_temp=min_temp, max_temp=3000.0,
                                              min_pressure=1000.0, max_pressure=1e7)
        db.KineticsComment.objects.create(kinetics=kinetics, kinetic_model=model)

    def test_other_ranges_stay_two_records(self):
        self.rate(0, 290.0)
        self.rate(1, 270.0)
        report = cleanup.merge_split_species(apply=True)
        self.assertEqual((report["reactions_merged"], report.get("kinetics_merged", 0)), (1, 0))
        self.assertEqual(sorted(db.Kinetics.objects.values_list("min_temp", flat=True)), [270.0, 290.0])
        self.assertEqual(db.Kinetics.objects.values("reaction_id").distinct().count(), 1)

    def test_the_same_range_merges(self):
        self.rate(0, 290.0)
        self.rate(1, 290.0)
        report = cleanup.merge_split_species(apply=True)
        self.assertEqual(report["kinetics_merged"], 1)
        (kinetics,) = db.Kinetics.objects.all()
        self.assertEqual(kinetics.kineticscomment_set.count(), 2)


class SplitChebyshevRangesTests(TestCase):
    """Databases imported before the range was in the identity."""

    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.cai, *_ = import_model(self.directory, "cai", CAI)
        self.zhang, *_ = import_model(self.directory, "zhang", CAI)
        self.jin, *_ = import_model(self.directory, "jin", JIN)
        old_import(self.jin, self.cai)
        self.shared = {k: v.pk for k, v in records(self.cai).items()}
        db.KineticsComment.objects.filter(kinetic_model=self.jin).update(comment="Jin's own comment")

    def run_command(self, *options):
        path = os.path.join(self.directory, "report.json")
        call_command("split_chebyshev_ranges", "--path", self.directory, "--report", path, *options,
                     stdout=open(os.devnull, "w"))
        with open(path) as handle:
            return json.load(handle)

    def state(self):
        return (sorted(db.KineticsComment.objects.values_list("pk", "kinetics_id")),
                sorted(db.Kinetics.objects.values_list("pk", "min_temp", "max_temp")))

    def test_the_old_import_shares_cais_record(self):
        self.assertEqual({k: v.pk for k, v in records(self.jin).items()}, self.shared)
        self.assertEqual(t_range(records(self.jin)[O2_RATE]), (290, 3000))

    def test_dry_run_writes_nothing(self):
        before = self.state()
        report = self.run_command()
        self.assertEqual(self.state(), before)
        self.assertEqual(report["counts"], {"links_moved": 2, "links_paired": 6, "records": 2, "records_changed": 2,
                                            "records_created": 2})

    def test_apply_gives_each_model_its_own_range(self):
        dry = self.run_command()
        report = self.run_command("--apply")
        self.assertEqual(report["counts"], dry["counts"])
        jin = records(self.jin)
        self.assertEqual((t_range(jin[O2_RATE]), t_range(jin[HO2_RATE])), ((270, 3000), (270, 4000)))
        for key, pk in self.shared.items():
            self.assertNotEqual(jin[key].pk, pk)
            self.assertEqual(jin[key].raw_data, records(self.cai)[key].raw_data)
            self.assertEqual(jin[key].reaction_id, records(self.cai)[key].reaction_id)
            self.assertEqual(jin[key].rate_fingerprint, kinetics_fingerprint(jin[key]))
            self.assertNotEqual(jin[key].rate_fingerprint, records(self.cai)[key].rate_fingerprint)
            for model in (self.cai, self.zhang):
                self.assertEqual((records(model)[key].pk, t_range(records(model)[key])), (pk, (290, 3000)))
        # The link rows moved: the same rows, with the model's comment.
        self.assertEqual(set(db.KineticsComment.objects.filter(kinetic_model=self.jin).values_list("comment", flat=True)),
                         {"Jin's own comment"})
        # The importer finds these records now.
        before = self.state()
        import_kinetics(os.path.join(self.directory, "jin", "RMG-Py-kinetics-library", "reactions.py"), self.jin, MODELS)
        self.assertEqual(self.state(), before)

    def test_second_run_changes_nothing(self):
        self.run_command("--apply")
        before = self.state()
        report = self.run_command("--apply")
        self.assertEqual(self.state(), before)
        self.assertEqual(report["counts"], {"links_paired": 6, "records": 4})

    def test_the_record_of_the_range_is_used_when_there_is_one(self):
        tran, *_ = import_model(self.directory, "tran", JIN)
        report = self.run_command("--apply")
        self.assertEqual((report["counts"]["links_moved_to_existing_records"], report["counts"].get("records_created", 0)),
                         (2, 0))
        self.assertEqual({k: v.pk for k, v in records(self.jin).items()}, {k: v.pk for k, v in records(tran).items()})

    def test_a_record_that_no_model_has_the_range_of_takes_the_range_of_most_links(self):
        db.Kinetics.objects.filter(pk__in=self.shared.values()).update(min_temp=300.0, max_temp=2000.0)
        report = self.run_command("--apply")
        self.assertEqual(report["counts"]["records_with_changed_range"], 2)
        for key, pk in self.shared.items():
            rate = db.Kinetics.objects.get(pk=pk)
            self.assertEqual((t_range(rate), rate.rate_fingerprint), ((290, 3000), kinetics_fingerprint(rate)))
            self.assertEqual(records(self.cai)[key].pk, pk)
            self.assertNotEqual(records(self.jin)[key].pk, pk)

    def test_a_link_without_a_library_stays_and_is_reported(self):
        missing = db.KineticModel.objects.create(model_name="missing")
        db.KineticsComment.objects.create(kinetic_model=missing, kinetics_id=self.shared[O2_RATE])
        report = self.run_command("--apply")
        self.assertEqual(report["counts"]["links_no_library"], 1)
        self.assertEqual([(r["model"], r["status"]) for r in report["links_without_own_range"]], [("missing", "no_library")])
        self.assertTrue(db.KineticsComment.objects.filter(kinetic_model=missing, kinetics_id=self.shared[O2_RATE]).exists())

    def test_model_option(self):
        report = split_chebyshev_ranges(self.directory, apply=False, models={"cai"})
        self.assertEqual(report["counts"], {"links_paired": 2, "records": 2})
