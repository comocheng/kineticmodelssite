"""The downloads of large models: on 1 Nov 2026 PCI2017/036-Rashidi (9,462 links) took 158 s
and CombFlame2017/111-Atef 307 s, so Cloudflare cut them off (524). Two causes: a dozen queries
per kinetics link, and one Cantera load (3-5 s) per orphaned ``duplicate: true``, which
Cantera reports one at a time."""
