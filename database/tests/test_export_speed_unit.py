"""The downloads of large models: on 1 Nov 2026 PCI2017/036-Rashidi (9,462 links) took 158 s
and CombFlame2017/111-Atef 307 s, so Cloudflare cut them off (524). Two causes: a dozen queries
per kinetics link, and one Cantera load (3-5 s) per orphaned ``duplicate: true``, which
Cantera reports one at a time."""
import os
import shutil
import tempfile

from django.db import connection
from django.test import TestCase
from django.test.utils import CaptureQueriesContext

from database import models as db
from database.scripts.import_rmg_models import import_kinetics, import_thermo
from database.services import exports
from database.tests.test_import_rmg_species_unit import MODELS, NASA_TEXT
from database.tests.test_repeated_species_export_unit import ADJ, REACTIONS

# Rates with no collider efficiencies; each efficiency still costs a query for its structure.
PLAIN = ["H2O2 + H <=> H2O + OH", "H + H + H2 <=> H2 + H2", "HO2 + HO2 <=> H2O2 + O2"]


def import_model(root, name, labels):
    """A model of the species of ADJ and the REACTIONS of these labels, imported as RMG-models."""
    folder = os.path.join(root, name)
    for library in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, library))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\n')
        for index, label in enumerate(ADJ):
            handle.write(f'entry(index={index}, label="{label}", molecule="""\n{ADJ[label]}\n""", '
                         f'thermo={NASA_TEXT}, shortDesc="""test""", longDesc="""""")\n')
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label, adjacency in ADJ.items():
            handle.write(f"{label}\n{adjacency}\n\n")
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, label in enumerate(labels):
            handle.write(f'entry(index={index}, label="{label}", degeneracy=1.0, '
                         f'kinetics={REACTIONS[label]}, shortDesc="""test""")\n')
    model = db.KineticModel.objects.create(model_name=name)
    import_thermo(thermo_path, model, MODELS)
    import_kinetics(kinetics_path, model, MODELS)
    return model


class ExportQueriesTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        directory = tempfile.mkdtemp()
        try:
            cls.small = import_model(directory, "small", PLAIN[:1])
            cls.large = import_model(directory, "large", PLAIN)
        finally:
            shutil.rmtree(directory)

    def queries(self, model):
        with CaptureQueriesContext(connection) as context:
            files = exports._generate_chemkin_files(model)
        return len(context.captured_queries), files

    def test_queries_do_not_grow_with_the_links(self):
        self.assertEqual((self.small.kineticscomment_set.count(), self.large.kineticscomment_set.count()), (1, 3))
        small, _ = self.queries(self.small)
        large, files = self.queries(self.large)
        self.assertEqual(small, large)
        (text,) = [v.decode() for k, v in files.items() if k.endswith("_chem.inp")]
        self.assertEqual(text.split("REACTIONS", 1)[1].count("<=>"), 3)

    def test_a_reaction_species_the_model_does_not_name_is_still_written(self):
        # The model names H2O2 + H <=> H2O + OH's species through its thermo; drop the name of OH.
        db.SpeciesName.objects.filter(kinetic_model=self.small, name="OH").delete()
        _, files = self.queries(self.small)
        (text,) = [v.decode() for k, v in files.items() if k.endswith("_chem.inp")]
        species = text.split("SPECIES", 1)[1].split("END", 1)[0].split()
        self.assertEqual(len(species), len(ADJ))
        self.assertEqual(text.split("REACTIONS", 1)[1].count("<=>"), 1)
