"""Two models that write the same reaction with different arrows. Every model with these species
and coefficients shares one reaction record, whose `reversible` flag is that of the first import,
and the exports used it: Gasoline_Surrogate's H + O2 => O + OH could come out as <=>. Each
model's kinetics link now keeps the model's own arrow, and the exports use it."""
import os
import re
import shutil
import tempfile

from django.test import TestCase

from api.serializers import KineticsCommentSerializer
from database import models as db
from database.scripts.import_rmg_models import import_kinetics, import_thermo
from database.services import exports
from database.services.cleanup import rebuild_model_links
from database.tests.test_import_rmg_species_unit import MODELS, NASA_TEXT
from database.tests.test_repeated_species_export_unit import ADJ, sides

SAME_RATE = "Arrhenius(A=(2.41e+13,'cm^3/(mol*s)'), n=0, Ea=(3970,'cal/mol'), T0=(1,'K'))"
# Each library: label -> (kinetics, reversible).
REVERSIBLE_MODEL = {
    "H2O2 + H <=> H2O + OH": (SAME_RATE, True),
    "HO2 + H <=> H2 + O2": ("Arrhenius(A=(1.66e+13,'cm^3/(mol*s)'), n=0, Ea=(820,'cal/mol'), T0=(1,'K'))", True),
    "H2 + OH <=> H2O + H": ("Arrhenius(A=(2.16e+08,'cm^3/(mol*s)'), n=1.51, Ea=(3430,'cal/mol'), T0=(1,'K'))", True),
}
IRREVERSIBLE_MODEL = {
    # The same rate: both models link one rate record.
    "H2O2 + H => H2O + OH": (SAME_RATE, False),
    # Another rate of the same reaction: a rate record of its own.
    "HO2 + H => H2 + O2": ("Arrhenius(A=(4e+13,'cm^3/(mol*s)'), n=0, Ea=(1000,'cal/mol'), T0=(1,'K'))", False),
}
# RMG-Py 4 refuses a reaction with four products, so the library does not import whole.
REFUSED = {"H2O2 + H2O2 => OH + OH + OH + OH": (SAME_RATE, False)}


def library(root, name, reactions):
    """<root>/<name>/ with a thermo library and a kinetics library of `reactions`."""
    folder = os.path.join(root, name)
    for sub in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, sub))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\n')
        for index, label in enumerate(ADJ):
            handle.write(f'entry(index={index}, label="{label}", molecule="""\n{ADJ[label]}\n""", '
                         f'thermo={NASA_TEXT}, shortDesc="""test""", longDesc="""""")\n')
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label, adjacency in ADJ.items():
            handle.write(f"{label}\n{adjacency}\n\n")
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, (kinetics, reversible)) in enumerate(reactions.items()):
            flag = "" if reversible else "reversible = False, "
            handle.write(f'entry(index={index}, label="{label}", degeneracy=1.0, {flag}'
                         f'kinetics={kinetics}, shortDesc="""test""")\n')
    return thermo_path, kinetics_path


class PerModelReversibilityTests(TestCase):
    @classmethod
    def setUpTestData(cls):
        cls.directory = tempfile.mkdtemp()
        cls.paths = {}
        for name, reactions in (("reversible", REVERSIBLE_MODEL), ("irreversible", IRREVERSIBLE_MODEL)):
            model = db.KineticModel.objects.create(model_name=name)
            thermo_path, kinetics_path = library(cls.directory, name, reactions)
            cls.paths[name] = (thermo_path, kinetics_path)
            import_thermo(thermo_path, model, MODELS)
            import_kinetics(kinetics_path, model, MODELS)
            setattr(cls, f"{name}_model", model)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.directory)
        super().tearDownClass()

    def link(self, model, *species):
        """The model's kinetics link of the reaction with these species (coefficient, name)."""
        names = dict(db.SpeciesName.objects.filter(kinetic_model=model).values_list("species_id", "name"))
        for link in db.KineticsComment.objects.filter(kinetic_model=model).select_related("kinetics__reaction"):
            stoichiometry = sorted((s.coeff, names[s.species_id])
                                   for s in link.kinetics.reaction.stoichiometry_set.all())
            if stoichiometry == sorted(species):
                return link
        raise AssertionError(f"{model} has no link for {species}")

    def chemkin_arrows(self, model):
        """sides -> the arrow of each reaction of the model's CHEMKIN export."""
        files = exports._generate_chemkin_files(model)
        (text,) = [v.decode() for k, v in files.items() if k.endswith("_chem.inp")]
        blocks = re.split(r"^(?=[^!\s]\S*=)", text.split("REACTIONS", 1)[1], flags=re.M)[1:]
        return {sides(block.split()[0]): re.search(r"<=>|=>|=", block.split()[0]).group() for block in blocks}

    def test_one_reaction_record_keeps_both_arrows(self):
        h2o2 = ((-1, "H2O2"), (-1, "H"), (1, "H2O"), (1, "OH"))
        first, second = self.link(self.reversible_model, *h2o2), self.link(self.irreversible_model, *h2o2)
        # One reaction record and one rate record, but each model's own arrow on its link.
        self.assertEqual(first.kinetics_id, second.kinetics_id)
        self.assertEqual((first.reversible, second.reversible), (True, False))
        ho2 = ((-1, "HO2"), (-1, "H"), (1, "H2"), (1, "O2"))
        first, second = self.link(self.reversible_model, *ho2), self.link(self.irreversible_model, *ho2)
        self.assertEqual(first.kinetics.reaction_id, second.kinetics.reaction_id)
        self.assertNotEqual(first.kinetics_id, second.kinetics_id)
        self.assertEqual((first.reversible, second.reversible), (True, False))
        # The shared reaction record still has the first import's flag.
        self.assertTrue(second.kinetics.reaction.reversible)

    def test_chemkin_export_writes_each_models_arrow(self):
        arrows = self.chemkin_arrows(self.reversible_model)
        self.assertEqual(arrows[sides("H2O2 + H <=> H2O + OH")], "<=>")
        self.assertEqual(arrows[sides("HO2 + H <=> H2 + O2")], "<=>")
        self.assertEqual(arrows[sides("H2 + OH <=> H2O + H")], "<=>")
        arrows = self.chemkin_arrows(self.irreversible_model)
        self.assertEqual(arrows, {sides("H2O2 + H => H2O + OH"): "=>", sides("HO2 + H => H2 + O2"): "=>"})

    def test_import_again_sets_the_arrow(self):
        h2o2 = ((-1, "H2O2"), (-1, "H"), (1, "H2O"), (1, "OH"))
        db.KineticsComment.objects.filter(kinetic_model=self.irreversible_model).update(reversible=True)
        import_kinetics(self.paths["irreversible"][1], self.irreversible_model, MODELS)
        self.assertFalse(self.link(self.irreversible_model, *h2o2).reversible)

    def test_rebuild_sets_the_arrow_and_keeps_it_on_kept_links(self):
        h2o2 = ((-1, "H2O2"), (-1, "H"), (1, "H2O"), (1, "OH"))
        control = self.link(self.reversible_model, (-1, "H2"), (-1, "OH"), (1, "H2O"), (1, "H"))
        # An old link to a rate the library does not make, as a library entry that RMG refuses
        # leaves it; the rebuild keeps it, with its arrow, because the library did not import whole.
        db.KineticsComment.objects.create(kinetics=control.kinetics, kinetic_model=self.irreversible_model,
                                          comment="old", reversible=False)
        db.KineticsComment.objects.filter(kinetic_model=self.irreversible_model).exclude(
            comment="old").update(reversible=True)
        thermo_path, kinetics_path = library(self.directory, "irreversible_refused",
                                             {**IRREVERSIBLE_MODEL, **REFUSED})
        result = rebuild_model_links(self.irreversible_model, thermo_path, kinetics_path)
        self.assertEqual(result["kinetics_links"]["kept_after_import_failure"], 1)
        self.assertFalse(self.link(self.irreversible_model, *h2o2).reversible)
        kept = db.KineticsComment.objects.get(kinetic_model=self.irreversible_model, kinetics=control.kinetics)
        self.assertEqual((kept.comment, kept.reversible), ("old", False))

    def test_api_serves_the_models_arrow(self):
        h2o2 = ((-1, "H2O2"), (-1, "H"), (1, "H2O"), (1, "OH"))
        self.assertIs(KineticsCommentSerializer(self.link(self.irreversible_model, *h2o2)).data["reversible"], False)
