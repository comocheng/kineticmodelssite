def write_model(root, name, labels, entries, lines, species_block=None):
    """An RMG-models folder with a kinetics library (no thermo library), SMILES.txt, import.sh and
    the CHEMKIN file."""
    folder = os.path.join(root, name)
    kinetics_dir = os.path.join(folder, "RMG-Py-kinetics-library")
    os.makedirs(kinetics_dir)
    with open(os.path.join(kinetics_dir, "dictionary.txt"), "w") as handle:
        for label in labels:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    with open(os.path.join(kinetics_dir, "reactions.py"), "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(entries):
            irreversible = "    reversible = False,\n" if " => " in label else ""
            handle.write(f'entry(\n    index = {index},\n    label = "{label}",\n    degeneracy = 1.0,\n'
                         f'{irreversible}    kinetics = {kinetics},\n'
                         f'    shortDesc = """The chemkin file reaction is {label}""",\n)\n\n')
    with open(os.path.join(folder, "SMILES.txt"), "w") as handle:
        handle.write("".join(f"{label}\tX\n" for label in labels))
    with open(os.path.join(folder, "import.sh"), "w") as handle:
        handle.write("python import.py \\\n\t--species chem.inp \\\n\t--reactions chem.inp \\\n")
    with open(os.path.join(folder, "chem.inp"), "w") as handle:
        handle.write(f"ELEMENTS C H O END\nSPECIES {species_block or ' '.join(labels)} END\nREACTIONS\n{lines}END\n")
    return os.path.join(kinetics_dir, "reactions.py")


class ChemkinLineColliderTests(SimpleTestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)

    def read(self, text, names=("R1H", "R4CH3", "CH4", "O2", "XX", "H", "HO2", "A", "B")):
        path = os.path.join(self.directory, "chem.inp")
        with open(path, "w") as handle:
            handle.write(f"REACTIONS\n{text}END\n")
        return chemkin_lines.read_reactions(path, set(names), 4.184)

    def test_colliders_and_low_rates(self):
        first, second, third = self.read(SERINYEL_LINES)
        self.assertEqual((first["collider"], second["collider"], third["collider"]), ("M", "M", "CH4"))
        self.assertEqual((first["reversible"], first["reactants"], first["products"]), (False, ["R1H", "R4CH3"], ["CH4"]))
        self.assertEqual(first["low"], (1.408e24, -1.8, 0.0))
        self.assertAlmostEqual(second["low"][2], 90900 * 4.184)
        (plain,) = self.read("H+O2+M=HO2+M 1e15 0 0\n")
        self.assertEqual((plain["collider"], plain["third_body"], plain["low"]), ("M", True, None))
        (none,) = self.read("A=>B 1e10 0 0\n")
        self.assertEqual((none["collider"], none["third_body"]), (None, False))

    def test_the_entry_as_rmg_reads_it(self):
        first = self.read(SERINYEL_LINES)[0]
        # Comments go; an efficiency of a species the library lacks (XX) is left out.
        self.assertEqual(chemkin_lines.kinetics_entry(first, {"R1H", "R4CH3", "CH4", "O2"}),
                         "R1H+R4CH3(+M)=>CH4(+M)         1.67E14     0.         0.\nO2/0.4/ CH4/3.0/\n"
                         "LOW /  1.408E24  -1.8   0.0 /\nTROE / 0.37 3315 61 /")

    def test_auxiliary_lines_of_an_unread_line_are_not_the_last_lines(self):
        first, second = self.read("A=>B 1e10 0 0\nA(+M)=>B(+M) 1e10\nLOW / 1e12 0 0 /\nA=B 2e10 0 0\n")
        self.assertEqual((first["low"], first["entry"]), (None, ["A=>B 1e10 0 0"]))
        self.assertEqual(second["A"], 2e10)

    def test_species_block_ends_at_its_end(self):
        # SPECIES ... END on one line: the reaction lines after it are not names (S-CH2+H was one).
        path = os.path.join(self.directory, "chem.inp")
        with open(path, "w") as handle:
            handle.write("ELEMENTS C H END\nSPECIES S-CH2 T-CH2 H END\nREACTIONS\nS-CH2+H => T-CH2+H 3e13 0 0\nEND\n"
                         "SPECIES\nAR ! argon\nHE END\n")
        self.assertEqual(chemkin_lines.species_names(path), {"S-CH2", "T-CH2", "H", "AR", "HE"})

    def test_rmg_units(self):
        self.assertEqual(chemkin_lines.rmg_units(4.184),
                         (["", "s^-1", "cm^3/(mol*s)", "cm^6/(mol^2*s)", "cm^9/(mol^3*s)", "cm^12/(mol^4*s)"], "cal/mol"))
        self.assertEqual(chemkin_lines.rmg_units(4184.0, molecules=True)[0][2], "cm^3/(molecule*s)")
        self.assertIsNone(chemkin_lines.rmg_units(chemkin_lines.EA_TO_J["EVOLTS"])[1])


class TwinLinesTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model = db.KineticModel.objects.create(model_name="m")

    def import_model(self, *args, **kwargs):
        self.kinetics_path = write_model(self.directory, self.model.model_name, *args, **kwargs)
        counts = import_kinetics(self.kinetics_path, self.model, MODELS)
        self.assertEqual((counts["failed"], counts["rejected"]), (0, 0))
        return counts

    def link(self, equation):
        return db.KineticsComment.objects.get(kinetic_model=self.model,
                                              comment=f"The chemkin file reaction is {equation}")

    def links(self):
        return db.KineticsComment.objects.filter(kinetic_model=self.model)

    def written(self, link):
        """The link's reaction as the export writes it: reactant and product names, and the arrow."""
        rows = link.kinetics.reaction.stoichiometry_set.select_related("species")
        name = lambda row: row.species.speciesname_set.get(kinetic_model=self.model).name
        side = lambda rows: sorted(name(row) for row in rows for _ in range(int(abs(row.coeff))))
        return (side(r for r in rows if r.coeff < 0), side(r for r in rows if r.coeff > 0), link.reversible)

    def efficiencies(self, link):
        return {e.species.speciesname_set.get(kinetic_model=self.model).name: e.efficiency
                for e in link.kinetics.efficiency_set.select_related("species")}

    def test_a_term_in_the_other_direction_gets_its_own_reaction(self):
        counts = self.import_model(("S-CH2", "T-CH2", "H"), (VRANCKX_ENTRY,), VRANCKX_LINES)
        self.assertEqual(counts["moved_terms"], 1)
        forward, reverse = self.link("S-CH2 + H => T-CH2 + H"), self.link("T-CH2 + H => S-CH2 + H")
        self.assertEqual(forward.kinetics.raw_data["type"], "arrhenius")
        self.assertEqual(forward.kinetics.raw_data["a"], 3e13)
        self.assertEqual((reverse.kinetics.raw_data["a"], reverse.kinetics.raw_data["n"]), (1.35e13, -0.013))
        self.assertEqual(self.written(forward), (["H", "S-CH2"], ["H", "T-CH2"], False))
        self.assertEqual(self.written(reverse), (["H", "T-CH2"], ["H", "S-CH2"], False))
        self.assertEqual(self.links().count(), 2)

    def test_terms_in_one_direction_stay_together(self):
        # Two DUPLICATE lines S-CH2 + H => T-CH2 + H: one link with both terms, as before.
        lines = VRANCKX_LINES.replace("T-CH2+H => S-CH2+H", "S-CH2+H => T-CH2+H")
        counts = self.import_model(("S-CH2", "T-CH2", "H"), (VRANCKX_ENTRY,), lines)
        self.assertNotIn("moved_terms", counts)
        self.assertEqual(self.link("S-CH2 + H => T-CH2 + H").kinetics.raw_data["type"], "multi_arrhenius")
        self.assertEqual(self.links().count(), 1)

    def test_lines_the_library_left_out_are_read_from_the_chemkin_file(self):
        counts = self.import_model(("R1H", "R4CH3", "CH4", "O2"), (SERINYEL_ENTRY,), SERINYEL_LINES,
                                   species_block="R1H R4CH3 CH4 O2 XX")
        self.assertEqual(counts["added_lines"], 2)
        kept = self.link("CH4 (+CH4) => R4CH3 + R1H (+CH4)")
        falloff, reverse = self.link("CH4 => R4CH3 + R1H"), self.link("R1H + R4CH3 => CH4")
        self.assertEqual(self.written(reverse), (["R1H", "R4CH3"], ["CH4"], False))
        self.assertEqual(self.written(falloff), (["CH4"], ["R1H", "R4CH3"], False))
        self.assertEqual(kept.kinetics.specific_collider.speciesname_set.get().name, "CH4")
        self.assertIsNone(falloff.kinetics.specific_collider)
        self.assertEqual(falloff.kinetics.reaction_id, kept.kinetics.reaction_id)
        data = falloff.kinetics.raw_data
        self.assertEqual((data["type"], data["low_arrhenius"]["a"], data["high_arrhenius"]["a"]), ("troe", 1.29e18, 2.4e16))
        self.assertEqual((data["alpha"], data["t3"], data["t1"], data["t2"]), (0.0, 1350.0, 1.0, 7830.0))
        self.assertEqual((reverse.kinetics.raw_data["low_arrhenius"]["a"], reverse.kinetics.raw_data["low_arrhenius"]["n"]),
                         (1.408e24, -1.8))
        # The model's efficiencies; XX, a species the library lacks, is left out.
        self.assertEqual(self.efficiencies(falloff), {"O2": 0.4, "CH4": 0.0})
        self.assertEqual(self.efficiencies(reverse), {"O2": 0.4, "CH4": 3.0})
        self.assertEqual(self.efficiencies(kept), {})

    def test_a_line_an_entry_holds_is_not_added(self):
        # An entry with the line's direction and collider is its line, though its rate differs
        # (RMG-models' conversion), and a line with an entry's rate is held in any direction.
        changed = (SERINYEL_ENTRY[0], SERINYEL_ENTRY[1].replace("2.4e+16", "2.5e+16"))
        lines = SERINYEL_LINES.split("CH4(+M)=>R4CH3")[0]
        reverse = ("CH4 => R4CH3 + R1H", "Troe(arrheniusHigh={}, arrheniusLow={}, alpha=0.37, T3=(3315,'K'), T1=(61,'K'))".format(
            ARR.format(a="1.67e+14", units="s^-1", n=0, e=0), ARR.format(a="1.408e+24", units="cm^3/(mol*s)", n=-1.8, e=0)))
        counts = self.import_model(("R1H", "R4CH3", "CH4", "O2"), (changed, reverse),
                                   lines + "CH4(+CH4)=>R4CH3+R1H(+CH4) 2.4E16 0 105.0E3\nLOW / 8.43E17 0 90.9E3 /\n")
        self.assertNotIn("added_lines", counts)
        self.assertEqual(self.links().count(), 2)

    def test_lines_of_a_reversible_reaction_are_not_added(self):
        reversible = ("R1H + R4CH3 <=> CH4", SERINYEL_ENTRY[1])
        counts = self.import_model(("R1H", "R4CH3", "CH4", "O2"), (reversible,), SERINYEL_LINES)
        self.assertNotIn("added_lines", counts)

    def test_importing_again_adds_nothing(self):
        self.import_model(("R1H", "R4CH3", "CH4", "O2"), (SERINYEL_ENTRY,), SERINYEL_LINES)
        before = [table.objects.count() for table in (db.Reaction, db.Kinetics, db.KineticsComment, db.Efficiency)]
        import_kinetics(self.kinetics_path, self.model, MODELS)
        self.assertEqual([table.objects.count() for table in (db.Reaction, db.Kinetics, db.KineticsComment, db.Efficiency)],
                         before)

    def test_an_import_of_some_types_adds_no_lines(self):
        self.kinetics_path = write_model(self.directory, "m", ("R1H", "R4CH3", "CH4", "O2"), (SERINYEL_ENTRY,),
                                         SERINYEL_LINES)
        counts = import_kinetics(self.kinetics_path, self.model, MODELS, only_types={"Troe"})
        self.assertNotIn("added_lines", counts)
        self.assertEqual(self.links().count(), 1)

    def test_rebuild_adds_the_lines(self):
        self.kinetics_path = write_model(self.directory, "m", ("R1H", "R4CH3", "CH4", "O2"), (SERINYEL_ENTRY,),
                                         SERINYEL_LINES)
        result = cleanup.rebuild_model_links(self.model, None, self.kinetics_path)
        self.assertEqual(result["kinetics_import"]["added_lines"], 2)
        self.assertEqual(result["kinetics_links"]["after"], 3)
        self.assertEqual(cleanup.integrity_report()["kinetics_links_not_their_equation"], 0)


class VariantTwinLinesTests(TestCase):
    """MatheuCH4 lines 1287 and 1305: CY[C(C)*CC*CC.] => CY[C(C)*CC.C*C] and back, both 5.5e8. The
    names are one structure (variants), and entry 498 holds both terms."""

    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model = db.KineticModel.objects.create(model_name="m")

    def test_each_direction_gets_its_rate(self):
        rate = ARR.format(a="5.5e+08", units="s^-1", n=0, e=0)
        entry = ("furop1 => furop2", f"MultiArrhenius(arrhenius=[{rate}, {rate}])")
        thermo_path, kinetics_path = model_folder(
            self.directory, "m", entries=(entry,), lines=("furop1=>furop2 5.5E+08 0 0", "furop2=>furop1 5.5E+08 0 0"))
        with open(kinetics_path) as handle:
            text = handle.read().replace("    duplicate = True,\n", "    duplicate = True,\n    reversible = False,\n")
        with open(kinetics_path, "w") as handle:
            handle.write(text)
        import_thermo(thermo_path, self.model, MODELS)
        counts = import_kinetics(kinetics_path, self.model, MODELS)
        self.assertEqual((counts["failed"], counts["moved_terms"]), (0, 1))
        forward = db.KineticsComment.objects.get(kinetic_model=self.model, comment="The chemkin file reaction is furop1 => furop2")
        reverse = db.KineticsComment.objects.get(kinetic_model=self.model, comment="The chemkin file reaction is furop2 => furop1")
        self.assertEqual((forward.kinetics.raw_data["type"], forward.kinetics.raw_data["a"]), ("arrhenius", 5.5e8))
        self.assertEqual((reverse.kinetics.raw_data["type"], reverse.kinetics.raw_data["a"]), ("arrhenius", 5.5e8))
        self.assertFalse(forward.reversible or reverse.reversible)
        record = lambda name: db.Species.objects.get(speciesname__kinetic_model=self.model, speciesname__name=name)
        reactant = lambda link: link.kinetics.reaction.stoichiometry_set.get(coeff__lt=0).species_id
        self.assertEqual((reactant(forward), reactant(reverse)), (record("furop1").pk, record("furop2").pk))
