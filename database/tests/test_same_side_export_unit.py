"""Reactions with the same species on both sides in Prometheus, as CombFlame2013/2291-Somers has
furop1 (+M) <=> furop2 (+M): the model gives two names to one structure, one species record. An
import before Nov 2026 kept only the first name for the record, so the export wrote furop1 (+M) <=>
furop1 (+M), which Cantera read as a reaction with furop1 for a named collider, and did not load
the file. The exports leave such a falloff reaction out and name it in a comment; the other types
load, so they are written as before. A model imported now names furop2 on its thermo link and on
the rates that write it, so furop2 is a species of the download and the model's reaction is
written."""
import os
import re
import shutil
import tempfile

from django.test import TestCase

from database import models as db
from database.scripts.import_rmg_models import import_kinetics, import_thermo
from database.services import exports
from database.tests.test_import_rmg_species_unit import MODELS, NASA_TEXT
from database.tests.test_repeated_species_export_unit import sides
from database.tests.test_model_names_unit import import_without_repeats

ALLYL = ("multiplicity 2\n1 C u0 p0 c0 {2,D} {4,S} {5,S}\n2 C u0 p0 c0 {1,D} {3,S} {6,S}\n"
         "3 C u1 p0 c0 {2,S} {7,S} {8,S}\n4 H u0 p0 c0 {1,S}\n5 H u0 p0 c0 {1,S}\n6 H u0 p0 c0 {2,S}\n"
         "7 H u0 p0 c0 {3,S}\n8 H u0 p0 c0 {3,S}")
ADJ = {
    "H": "multiplicity 2\n1 H u1 p0 c0",
    "H2": "1 H u0 p0 c0 {2,S}\n2 H u0 p0 c0 {1,S}",
    # Two names of one structure, as furop1 and furop2.
    "C3H5-A": ALLYL,
    "C3H5-X": ALLYL,
    "C3H6": "1 C u0 p0 c0 {2,D} {4,S} {5,S}\n2 C u0 p0 c0 {1,D} {3,S} {6,S}\n"
            "3 C u0 p0 c0 {2,S} {7,S} {8,S} {9,S}\n4 H u0 p0 c0 {1,S}\n5 H u0 p0 c0 {1,S}\n"
            "6 H u0 p0 c0 {2,S}\n7 H u0 p0 c0 {3,S}\n8 H u0 p0 c0 {3,S}\n9 H u0 p0 c0 {3,S}",
}
ARRHENIUS = "Arrhenius(A=({A},'{units}'), n={n}, Ea=({Ea},'cal/mol'), T0=(1,'K'))"
REACTIONS = {
    # Somers' furop1 <=> furop2 rate.
    "C3H5-A <=> C3H5-X": "Troe(arrheniusHigh=" + ARRHENIUS.format(A=2.2e12, units="s^-1", n=0, Ea=5640)
                         + ", arrheniusLow=" + ARRHENIUS.format(A=7.385e8, units="cm^3/(mol*s)", n=1.36, Ea=-140)
                         + ", alpha=0.1116, T3=(352,'K'), T1=(6.85e12,'K'), T2=(492,'K'), efficiencies={})",
    "C3H5-A + H <=> C3H5-X + H": ARRHENIUS.format(A=1e13, units="cm^3/(mol*s)", n=0, Ea=0),
    # The same species on both sides in the model itself, as Gasoline_2's IC5H7 + IC5H8 <=> IC5H8 + IC5H7.
    "C3H6 + C3H5-A <=> C3H5-A + C3H6": ARRHENIUS.format(A=1e11, units="cm^3/(mol*s)", n=0, Ea=10000),
    "C3H5-A + H <=> C3H6": ARRHENIUS.format(A=2e14, units="cm^3/(mol*s)", n=0, Ea=0),
    "C3H6 + H <=> C3H5-X + H2": ARRHENIUS.format(A=1.7e5, units="cm^3/(mol*s)", n=2.5, Ea=2490),
}
LEFT_OUT = ["C3H5-A <=> C3H5-X"]
# Both names are written as the first one, C3H5-A.
EXPORTED = ["C3H5-A + H <=> C3H5-A + H", "C3H6 + C3H5-A <=> C3H5-A + C3H6",
            "C3H5-A + H <=> C3H6", "C3H6 + H <=> C3H5-A + H2"]


def one_name(equation):
    """The equation with C3H5-A for both names: a model imported before variant records has one
    record for both, written as C3H5-A (once listed twice, as C3H5-A01: furop101 in Somers)."""
    return sides(re.sub(r"C3H5-A\d*", "C3H5-A", equation))


def library(root):
    """<root>/somers/ with a thermo library and a kinetics library of REACTIONS."""
    folder = os.path.join(root, "somers")
    for name in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, name))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\n')
        for index, label in enumerate(ADJ):
            handle.write(f'entry(index={index}, label="{label}", molecule="""\n{ADJ[label]}\n""", '
                         f'thermo={NASA_TEXT}, shortDesc="""test""", longDesc="""""")\n')
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label, adjacency in ADJ.items():
            handle.write(f"{label}\n{adjacency}\n\n")
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(REACTIONS.items()):
            handle.write(f'entry(index={index}, label="{label}", degeneracy=1.0, kinetics={kinetics}, '
                         f'shortDesc="""The chemkin file reaction is {label}""")\n')
    return thermo_path, kinetics_path


def chemkin_text(model):
    files = exports._generate_chemkin_files(model)
    (text,) = [v.decode() for k, v in files.items() if k.endswith("_chem.inp")]
    return text


class SameSideExportTests(TestCase):
    """A model imported before Nov 2026 (the databases until their models are rebuilt)."""

    @classmethod
    def setUpTestData(cls):
        directory = tempfile.mkdtemp()
        try:
            cls.model = db.KineticModel.objects.create(model_name="somers")
            thermo_path, kinetics_path = library(directory)
            cls.counts = import_without_repeats(thermo_path, kinetics_path, cls.model)
        finally:
            shutil.rmtree(directory)

    def chemkin_text(self):
        return chemkin_text(self.model)

    def test_the_two_names_are_one_species(self):
        self.assertEqual((self.counts["imported"], self.counts["failed"]), (5, 0))
        names = db.SpeciesName.objects.filter(kinetic_model=self.model, name__in=["C3H5-A", "C3H5-X"])
        self.assertEqual(len({name.species_id for name in names}), 1)

    def test_chemkin_export_leaves_them_out_and_names_them(self):
        text = self.chemkin_text()
        written = [line.split()[0] for line in text.split("REACTIONS", 1)[1].splitlines()
                   if "=" in line and not line.lstrip().startswith("!")]
        self.assertCountEqual(map(one_name, written), map(sides, EXPORTED))
        header = [line for line in text.splitlines() if line.startswith("! kinetics ")]
        self.assertEqual(sorted(line.split(": ", 1)[1] for line in header), sorted(LEFT_OUT))
        self.assertTrue(text.startswith("! Prometheus did not write 1 falloff reaction(s)"))

    def test_the_record_of_two_names_is_written_once_under_the_first(self):
        species = self.chemkin_text().split("SPECIES", 1)[1].split("END", 1)[0].split()
        self.assertEqual([name for name in species if name.startswith("C3H5")], ["C3H5-A"])

    def test_cantera_file_loads_and_says_what_was_left_out(self):
        import cantera as ct
        import yaml
        content = exports.build_cantera_yaml(self.model).content.decode()
        solution = ct.Solution(yaml=content)
        self.assertCountEqual([one_name(r.equation) for r in solution.reactions()], map(sides, EXPORTED))
        description = yaml.safe_load(content)["description"]
        for equation in LEFT_OUT:
            self.assertIn(equation, description)


# The model's reactions as the exports write them: the Troe rate with (+M).
WRITTEN = [label.replace(" <=> ", " (+M) <=> ") + " (+M)" if label == "C3H5-A <=> C3H5-X" else label
           for label in REACTIONS]


class ModelNamesExportTests(TestCase):
    """The same model imported now: C3H5-X is a second name of the record with its own thermo
    link, so every reaction of the model is written, the falloff reaction too."""

    @classmethod
    def setUpTestData(cls):
        directory = tempfile.mkdtemp()
        try:
            cls.model = db.KineticModel.objects.create(model_name="somers")
            thermo_path, kinetics_path = library(directory)
            import_thermo(thermo_path, cls.model, MODELS)
            cls.counts = import_kinetics(kinetics_path, cls.model, MODELS)
        finally:
            shutil.rmtree(directory)

    def test_the_two_names_are_one_record(self):
        self.assertEqual((self.counts["imported"], self.counts["failed"]), (5, 0))
        names = db.SpeciesName.objects.filter(kinetic_model=self.model, name__in=["C3H5-A", "C3H5-X"])
        self.assertEqual(len({name.species_id for name in names}), 1)
        self.assertEqual(db.ThermoComment.objects.filter(kinetic_model=self.model, species_name__in=names).count(), 2)

    def test_chemkin_export_writes_the_models_reactions(self):
        text = chemkin_text(self.model)
        written = [line.split()[0] for line in text.split("REACTIONS", 1)[1].splitlines()
                   if "=" in line and not line.lstrip().startswith("!")]
        self.assertCountEqual(map(sides, written), map(sides, WRITTEN))
        self.assertFalse([line for line in text.splitlines() if line.startswith("! kinetics ")])
        species = text.split("SPECIES", 1)[1].split("END", 1)[0].split()
        # Each name once, as the model writes it (older downloads: C3H5-A(3)); no C3H5-A01.
        self.assertEqual(sorted(re.sub(r"\(\d+\)$", "", name) for name in species if name.startswith("C3H5")),
                         ["C3H5-A", "C3H5-X"])

    def test_cantera_file_loads_with_the_falloff_reaction(self):
        import cantera as ct
        solution = ct.Solution(yaml=exports.build_cantera_yaml(self.model).content.decode())
        self.assertCountEqual([sides(r.equation) for r in solution.reactions()], map(sides, WRITTEN))
        (falloff,) = [r for r in solution.reactions() if r.reaction_type.startswith("falloff")]
        self.assertEqual(sides(falloff.equation), sides("C3H5-A (+M) <=> C3H5-X (+M)"))
