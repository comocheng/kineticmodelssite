# The a6 (H/R) coefficient of each label's thermo: furop2 lies below furop1, as in the model.
A6 = {"furop1": 10000.0, "furop2": 8500.0}
LABELS = ("furop1", "furop2", "H", "CH2CO", "C2H3", "C2H4")
REACTIONS = (
    ("furop1 <=> furop2", "Arrhenius(A=(1e+12,'s^-1'), n=0, Ea=(30000,'cal/mol'), T0=(1,'K'))"),
    ("furop1 + H <=> CH2CO + C2H3",
     "Arrhenius(A=(1e+13,'cm^3/(mol*s)'), n=0, Ea=(2000,'cal/mol'), T0=(1,'K'))"),
    ("furop2 + H <=> CH2CO + C2H3",
     "Arrhenius(A=(2e+13,'cm^3/(mol*s)'), n=0, Ea=(2000,'cal/mol'), T0=(1,'K'))"),
    ("C2H3 + H <=> C2H4",
     "ThirdBody(arrheniusLow=Arrhenius(A=(1e+20,'cm^6/(mol^2*s)'), n=-1, Ea=(0,'cal/mol'), T0=(1,'K')), "
     "efficiencies={'C=C=CC=O': 3.0})"),
)


def thermo_text(labels):
    entries = []
    for index, label in enumerate(labels):
        coeffs = f"[3.0,0,0,0,0,{A6.get(label, 1000.0)},5.0]"
        entries.append(f'''entry(
    index = {index},
    label = "{label}",
    molecule =
"""
{ADJ[label]}
""",
    thermo = NASA(
        polynomials = [
            NASAPolynomial(coeffs={coeffs}, Tmin=(300,'K'), Tmax=(1000,'K')),
            NASAPolynomial(coeffs={coeffs}, Tmin=(1000,'K'), Tmax=(5000,'K')),
        ],
        Tmin = (300,'K'),
        Tmax = (5000,'K'),
    ),
    shortDesc = """test {label}""",
    longDesc = """""",
)
''')
    return 'name = "test"\nshortDesc = ""\nlongDesc = """"""\n' + "\n".join(entries)


def kinetics_files(directory, labels=LABELS, reactions=REACTIONS):
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label in labels:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    with open(os.path.join(directory, "reactions.py"), "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(reactions):
            handle.write(f'''entry(
    index = {index},
    label = "{label}",
    degeneracy = 1.0,
    kinetics = {kinetics},
    shortDesc = """The chemkin file reaction is {label}""",
)

''')
    return os.path.join(directory, "reactions.py")


def model_folder(root, name, labels=LABELS):
    """<root>/<name>/ laid out like an RMG-models folder, with a thermo and a kinetics library."""
    folder = os.path.join(root, name)
    os.makedirs(os.path.join(folder, "RMG-Py-thermo-library"))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write(thermo_text(labels))
    return thermo_path, kinetics_files(os.path.join(folder, "RMG-Py-kinetics-library"))


def furop():
    return Molecule().from_adjacency_list(FUROP)


def import_without_variants(thermo_path, kinetics_path, model):
    """Import as the importer did before variant records: a later label of a structure on the
    first label's record, and its reactions merged with the first label's. Returns the kinetics
    counts."""
    real = importer.load_thermo_library

    def without_repeats(*args, **kwargs):
        library = real(*args, **kwargs)
        library.repeats = {}
        return library

    with mock.patch.object(importer, "load_thermo_library", side_effect=without_repeats):
        import_thermo(thermo_path, model, MODELS)
    return import_kinetics(kinetics_path, model, MODELS, variants={})


class VariantLoaderTests(SimpleTestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)

    def thermo(self, labels):
        path = os.path.join(self.directory, "ThermoLibrary.py")
        with open(path, "w") as handle:
            handle.write(thermo_text(labels))
        library = TolerantThermoLibrary(label="test")
        library.load(path, local_context=dict(THERMO_CONTEXT))
        return library

    def test_conformers_are_all_kept(self):
        library = self.thermo(["furop1", "furop2", "H", "furop3"])
        self.assertEqual(list(library.entries), ["furop1", "furop2", "H", "furop3"])
        self.assertEqual(library.repeats, {"furop2": "furop1", "furop3": "furop1"})
        self.assertEqual(library.skipped, [])

    def test_resonance_forms_with_one_key_are_two_species(self):
        library = self.thermo(["C4H71-3", "C4H72-1"])
        self.assertEqual(list(library.entries), ["C4H71-3", "C4H72-1"])
        self.assertEqual(library.repeats, {"C4H72-1": "C4H71-3"})

    def kinetics(self, declared_variants):
        library = TolerantKineticsLibrary(label="test")
        library.declared_variants = declared_variants
        library.load(kinetics_files(self.directory), local_context=importer.kinetics_local_context())
        return {entry.label: type(entry.data).__name__ for entry in library.entries.values()}

    def test_reactions_of_two_conformers_stay_apart(self):
        rates = self.kinetics({"furop2": "test: furop2"})
        self.assertEqual(rates["furop1 + H <=> CH2CO + C2H3"], "Arrhenius")
        self.assertEqual(rates["furop2 + H <=> CH2CO + C2H3"], "Arrhenius")
        self.assertEqual(len(rates), 4)

    def test_without_variants_they_are_merged_as_rmg_does(self):
        rates = self.kinetics(None)
        self.assertEqual(rates["furop1 + H <=> CH2CO + C2H3"], "MultiArrhenius")
        self.assertNotIn("furop2 + H <=> CH2CO + C2H3", rates)


class VariantImportTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model = db.KineticModel.objects.create(model_name="m")
        self.thermo_path, self.kinetics_path = model_folder(self.directory, "m")

    def record(self, name, model=None):
        return db.Species.objects.get(speciesname__kinetic_model=model or self.model,
                                      speciesname__name=name)

    def names(self, species):
        return sorted(species.speciesname_set.values_list("name", flat=True))

    def import_model(self, model=None, thermo_path=None, kinetics_path=None):
        thermo = import_thermo(thermo_path or self.thermo_path, model or self.model, MODELS)
        kinetics = import_kinetics(kinetics_path or self.kinetics_path, model or self.model, MODELS)
        self.assertEqual((thermo["failed"], kinetics["failed"], kinetics["rejected"]), (0, 0, 0))
        return thermo, kinetics

    def kinetics(self, equation):
        """The model's kinetics row of the library entry with this CHEMKIN equation."""
        return db.KineticsComment.objects.get(
            kinetic_model=self.model, comment=f"The chemkin file reaction is {equation}").kinetics

    def test_later_label_gets_its_own_record_and_thermo(self):
        counts = import_thermo(self.thermo_path, self.model, MODELS)
        self.assertEqual((counts["failed"], counts["skipped_duplicates"]), (0, []))
        self.assertEqual(counts["repeats"], {"furop2": "furop1"})
        first, second = self.record("furop1"), self.record("furop2")
        self.assertNotEqual(first.pk, second.pk)
        self.assertEqual((first.variant, second.variant), ("", variant_name(self.model, "furop2")))
        self.assertEqual(second.variant, "m: furop2")
        self.assertEqual(set(first.isomers.all()), set(second.isomers.all()))
        self.assertEqual(second.hash, get_species_hash(second.isomers.all(), "", second.variant))
        self.assertEqual(first.thermo_set.get().coeffs_poly1[5], 10000.0)
        self.assertEqual(second.thermo_set.get().coeffs_poly1[5], 8500.0)
        self.assertEqual((self.names(first), self.names(second)), (["furop1"], ["furop2"]))

    def test_isomerisation_keeps_both_species(self):
        _, counts = self.import_model()
        self.assertEqual(counts["imported"], 4)
        first, second = self.record("furop1"), self.record("furop2")
        reaction = self.kinetics("furop1 <=> furop2").reaction
        self.assertEqual(set(reaction.stoichiometry_set.values_list("species_id", "coeff")),
                         {(first.pk, -1.0), (second.pk, 1.0)})
        # Comparison across models stays by structure, so both sides have one key.
        left, right = reaction.canonical_key.split(" = ")
        self.assertEqual(left, right)
        # furop2 + H keeps its own reaction and rate.
        one = self.kinetics("furop1 + H <=> CH2CO + C2H3")
        two = self.kinetics("furop2 + H <=> CH2CO + C2H3")
        self.assertNotEqual(one.reaction_id, two.reaction_id)
        self.assertIn(second.pk, two.reaction.stoichiometry_set.values_list("species_id", flat=True))
        self.assertEqual((one.raw_data["a"], two.raw_data["a"]), (1e13, 2e13))
        # A collider efficiency is written as a SMILES: the shared record.
        self.assertEqual(db.Efficiency.objects.get(kinetics__kineticscomment__kinetic_model=self.model)
                         .species_id, first.pk)

    def test_kinetics_first_gives_the_same_records(self):
        import_kinetics(self.kinetics_path, self.model, MODELS)
        second = self.record("furop2")
        self.assertEqual(second.variant, "m: furop2")
        import_thermo(self.thermo_path, self.model, MODELS)
        self.assertEqual(self.record("furop2").pk, second.pk)
        self.assertEqual(second.thermo_set.get().coeffs_poly1[5], 8500.0)
        self.assertEqual(db.Species.objects.filter(isomers__formula__formula="C4H4O").distinct().count(), 2)

    def test_each_model_has_its_own_variant_record(self):
        other = db.KineticModel.objects.create(model_name="n")
        thermo_path, kinetics_path = model_folder(self.directory, "n")
        self.import_model()
        self.import_model(other, thermo_path, kinetics_path)
        self.assertEqual(self.record("furop1").pk, self.record("furop1", other).pk)
        self.assertNotEqual(self.record("furop2").pk, self.record("furop2", other).pk)
        self.assertEqual(self.record("furop2", other).variant, "n: furop2")
        self.assertEqual(db.Species.objects.filter(isomers__formula__formula="C4H4O").distinct().count(), 3)

    def test_importing_again_adds_nothing(self):
        def counts():
            return [table.objects.count() for table in (
                db.Species, db.Reaction, db.Kinetics, db.SpeciesName, db.ThermoComment, db.KineticsComment)]
        self.import_model()
        before = counts()
        self.import_model()
        self.assertEqual(counts(), before)

    def test_structure_lookups_give_the_shared_record(self):
        self.import_model()
        first = self.record("furop1")
        self.assertEqual(inchikey_species_map()[furop().to_inchi_key()], first.pk)
        inchi = standard_inchi(first.isomers.get().inchi)
        self.assertEqual(set(_by_standard_inchi(inchi)), {first.pk})
        # Another source (a thermo provider, another model's entry) means the shared record.
        self.assertEqual(get_or_create_species(None, "", [furop()], MODELS).pk, first.pk)

    def test_provider_thermo_goes_to_the_shared_record(self):
        # A kinetics import can make the variant record first, so it is the older one.
        variant = get_or_create_species(self.model, "furop2", [furop()], MODELS, variant="m: furop2")
        shared = get_or_create_species(None, "", [furop()], MODELS)
        self.assertLess(variant.pk, shared.pk)
        structure = db.Structure.objects.get(isomer__species=shared)
        record = thermo_sources.save_record(
            None, provider="rmg_thermo_library", structure=structure, external_id="lib:furop",
            source_version="test", label="furop")
        self.assertEqual(record.species_id, shared.pk)

    def test_clean_up_keeps_the_variant_record(self):
        self.import_model()
        first, second = self.record("furop1"), self.record("furop2")
        self.assertFalse(any({first.pk, second.pk} <= set(group) for group in cleanup.split_groups()))
        report = cleanup.integrity_report()
        self.assertEqual((report["split_species"], report["species_with_stale_hash"],
                          report["model_names_on_2plus_records"], report["variant_species"],
                          report["names_not_their_variant"]), (0, 0, 0, 1, 0))
        db.SpeciesName.objects.create(species=second, kinetic_model=self.model, name="furop1")
        self.assertEqual(cleanup.integrity_report()["names_not_their_variant"], 1)

    def test_rebuild_moves_a_merged_name_to_its_record(self):
        # What the old importer left: furop2 on furop1's record, furop1 <=> furop2 stored as
        # furop1 <=> furop1, and furop2 + H merged into the rate of furop1 + H.
        import_without_variants(self.thermo_path, self.kinetics_path, self.model)
        first = self.record("furop1")
        self.assertEqual(self.names(first), ["furop1", "furop2"])
        same_side = self.kinetics("furop1 <=> furop2")
        self.assertEqual(set(same_side.reaction.stoichiometry_set.values_list("species_id", flat=True)),
                         {first.pk})
        self.assertEqual(db.KineticsComment.objects.filter(kinetic_model=self.model).count(), 3)

        result = cleanup.rebuild_model_links(self.model, self.thermo_path, self.kinetics_path)
        second = self.record("furop2")
        self.assertEqual((self.names(first), self.names(second)), (["furop1"], ["furop2"]))
        self.assertEqual(second.variant, "m: furop2")
        self.assertEqual(result["kinetics_links"]["after"], 4)
        reaction = self.kinetics("furop1 <=> furop2").reaction
        self.assertNotEqual(reaction.pk, same_side.reaction_id)
        self.assertEqual(set(reaction.stoichiometry_set.values_list("species_id", "coeff")),
                         {(first.pk, -1.0), (second.pk, 1.0)})
        report = cleanup.integrity_report()
        self.assertEqual((report["names_not_their_variant"], report["model_names_on_2plus_records"]), (0, 0))
