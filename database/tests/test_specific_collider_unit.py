"""Falloff rates for one collider, H + O2 (+AR) <=> HO2 (+AR), as CombFlame2015/3755-Konnov
writes them. The RMG library names the collider only in the label (efficiencies={})."""
import os
import re
import shutil
import tempfile

import yaml
from django.test import SimpleTestCase, TestCase
from rmgpy.kinetics import Arrhenius, Troe
from rmgpy.molecule import Molecule
from rmgpy.reaction import Reaction as RMGReaction
from rmgpy.species import Species as RMGSpecies

from database import models as db
from database.scripts.import_rmg_models import import_kinetics, import_thermo
from database.services import cleanup, exports
from database.tests.test_import_rmg_species_unit import ADJ, MODELS, thermo_library_text

LABELS = ("H", "O2", "HO2", "AR", "H2O")
HIGH = "arrheniusHigh=Arrhenius(A=(4.66e+12,'cm^3/(mol*s)'), n=0.44, Ea=(0,'cal/mol'), T0=(1,'K'))"
# label -> (low-pressure A, n, alpha, efficiencies)
KONNOV = {
    "H + O2 <=> HO2": (1.74e19, -1.232, 0.67, "{'O': 0.0, '[Ar]': 0.0, '[O][O]': 0.0}"),
    "H + O2 (+AR) <=> HO2 (+AR)": (4.57e18, -1.12, 0.5, "{}"),
    "H + O2 (+O2) <=> HO2 (+O2)": (5.69e18, -1.094, 0.5, "{}"),
    "H + O2 (+H2O) <=> HO2 (+H2O)": (3.67e19, -1.0, 0.8, "{}"),
}
# An older conversion that lost the collider: the (+AR) rate written as (+M).
LOST = {"H + O2 <=> HO2": KONNOV["H + O2 (+AR) <=> HO2 (+AR)"]}


def collider_model(root, name, entries):
    """<root>/<name>/ with a thermo library and a kinetics library of these Troe entries."""
    folder = os.path.join(root, name)
    for library in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"):
        os.makedirs(os.path.join(folder, library))
    thermo_path = os.path.join(folder, "RMG-Py-thermo-library", "ThermoLibrary.py")
    with open(thermo_path, "w") as handle:
        handle.write(thermo_library_text(LABELS))
    directory = os.path.join(folder, "RMG-Py-kinetics-library")
    with open(os.path.join(directory, "dictionary.txt"), "w") as handle:
        for label in LABELS:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    text = 'name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n'
    for index, (label, (a, n, alpha, efficiencies)) in enumerate(entries.items()):
        text += f'''
entry(
    index = {index},
    label = "{label}",
    degeneracy = 1.0,
    kinetics = Troe({HIGH}, arrheniusLow=Arrhenius(A=({a},'cm^6/(mol^2*s)'), n={n}, Ea=(0,'cal/mol'), T0=(1,'K')), alpha={alpha}, T3=(1,'K'), T1=(1e+10,'K'), efficiencies={efficiencies}),
    shortDesc = """The chemkin file reaction is {label}""",
)
'''
    kinetics_path = os.path.join(directory, "reactions.py")
    with open(kinetics_path, "w") as handle:
        handle.write(text)
    return thermo_path, kinetics_path


def import_model(root, name, entries):
    model = db.KineticModel.objects.create(model_name=name)
    thermo_path, kinetics_path = collider_model(root, name, entries)
    import_thermo(thermo_path, model, MODELS)
    counts = import_kinetics(kinetics_path, model, MODELS)
    return model, thermo_path, kinetics_path, counts


def rates(model):
    """collider name ("M" for none) -> the model's rate record of H + O2 = HO2."""
    names = dict(db.SpeciesName.objects.filter(kinetic_model=model).values_list("species_id", "name"))
    return {names[k.specific_collider_id] if k.specific_collider_id else "M": k
            for k in db.Kinetics.objects.filter(kineticscomment__kinetic_model=model)}


def collider_terms(equations):
    """The (+X) terms of each equation, without RMG's species index: (+AR(4)) -> AR."""
    return sorted(re.sub(r"\(\d+\)$", "", term.strip())
                  for equation in equations for term in re.findall(r"\(\+\s*([^()]+(?:\(\d+\))?)\)", equation)[:1])


class SpecificColliderImportTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model, self.thermo_path, self.kinetics_path, self.counts = import_model(
            self.directory, "konnov", KONNOV)

    def test_each_collider_keeps_its_own_rate(self):
        self.assertEqual((self.counts["imported"], self.counts["failed"]), (4, 0))
        records = rates(self.model)
        self.assertEqual(set(records), {"M", "AR", "O2", "H2O"})
        # The collider is the model's own species record, not a new one.
        ar = db.Species.objects.get(speciesname__kinetic_model=self.model, speciesname__name="AR")
        self.assertEqual(records["AR"].specific_collider, ar)
        for name in ("AR", "O2", "H2O"):
            self.assertFalse(records[name].efficiency_set.exists())
        self.assertEqual(records["M"].efficiency_set.count(), 3)

    def test_the_same_rate_for_m_is_another_record(self):
        other, *_ = import_model(self.directory, "lost", LOST)
        (general,) = rates(other).values()
        self.assertIsNone(general.specific_collider)
        self.assertEqual(general.raw_data, rates(self.model)["AR"].raw_data)
        self.assertNotEqual(general.pk, rates(self.model)["AR"].pk)

    def test_importing_again_finds_the_same_records(self):
        before = sorted(db.Kinetics.objects.values_list("pk", "specific_collider_id"))
        counts = import_kinetics(self.kinetics_path, self.model, MODELS)
        self.assertEqual((counts["imported"], counts["failed"]), (4, 0))
        self.assertEqual(sorted(db.Kinetics.objects.values_list("pk", "specific_collider_id")), before)
        self.assertEqual(db.KineticsComment.objects.filter(kinetic_model=self.model).count(), 4)

    def test_rmg_reaction_has_the_collider(self):
        collider = rates(self.model)["AR"].to_rmg().specific_collider
        self.assertTrue(collider.is_isomorphic(Molecule(smiles="[Ar]")))
        self.assertIsNone(rates(self.model)["M"].to_rmg().specific_collider)

    def test_api_gives_the_collider(self):
        records = rates(self.model)
        data = self.client.get(f"/api/kinetics/{records['AR'].pk}/").json()
        self.assertEqual(data["specific_collider"], records["AR"].specific_collider_id)
        self.assertEqual(data["efficiency_set"], [])
        self.assertIsNone(self.client.get(f"/api/kinetics/{records['M'].pk}/").json()["specific_collider"])

    def test_chemkin_export_writes_each_collider(self):
        (text,) = [v.decode() for k, v in exports._generate_chemkin_files(self.model).items() if k.endswith("_chem.inp")]
        equations = [line.split()[0] for line in text.splitlines() if "<=>" in line and "HO2" in line]
        self.assertEqual(collider_terms(equations), ["AR", "H2O", "M", "O2"])
        # (+M) gives AR, O2 and H2O efficiency 0, so no two of these act on the same collider.
        self.assertNotIn("DUPLICATE", text)

    def test_cantera_file_keeps_each_collider(self):
        import cantera as ct
        content = exports.build_cantera_yaml(self.model).content.decode()
        solution = ct.Solution(yaml=content)
        equations = [r.equation for r in solution.reactions()]
        self.assertEqual(collider_terms(equations), ["AR", "H2O", "M", "O2"])
        self.assertFalse(any(r.get("duplicate") for r in yaml.safe_load(content)["reactions"]))


class SpecificColliderRebuildTests(TestCase):
    """A model imported before colliders were kept, rebuilt with the current importer."""

    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.other, *_ = import_model(self.directory, "lost", LOST)
        self.model, self.thermo_path, self.kinetics_path, _ = import_model(self.directory, "konnov", KONNOV)
        # What the older import left: the (+AR) entry linked to the (+M) record of the same rate.
        self.shared = rates(self.other)["M"]
        ar_rate = rates(self.model)["AR"]
        db.KineticsComment.objects.filter(kinetics=ar_rate).update(kinetics=self.shared)
        ar_rate.delete()

    def test_rebuild_links_a_record_with_the_collider(self):
        result = cleanup.rebuild_model_links(self.model, self.thermo_path, self.kinetics_path)
        self.assertEqual((result["kinetics_links"]["removed"], result["kinetics_links"]["added"]), (1, 1))
        records = rates(self.model)
        self.assertEqual(set(records), {"M", "AR", "O2", "H2O"})
        self.assertEqual(records["AR"].raw_data, self.shared.raw_data)
        # The other model keeps its (+M) record.
        self.assertEqual(rates(self.other), {"M": self.shared})

    def test_collider_species_is_kept_by_its_rate(self):
        cleanup.rebuild_model_links(self.model, self.thermo_path, self.kinetics_path)
        ar = rates(self.model)["AR"].specific_collider
        db.SpeciesName.objects.filter(species=ar).delete()
        cleanup.prune_unlinked_rows(apply=True)
        self.assertTrue(db.Species.objects.filter(pk=ar.pk).exists())


class DuplicateMarkingTests(SimpleTestCase):
    """Cantera takes two falloff reactions of the same species for duplicates only when some
    collider acts in both."""

    def setUp(self):
        self.species = {label: RMGSpecies(label=label).from_smiles(smiles) for label, smiles in
                        (("H", "[H]"), ("O2", "[O][O]"), ("HO2", "O[O]"), ("AR", "[Ar]"), ("H2O", "O"))}

    def reaction(self, collider=None, efficiencies=None):
        arrhenius = Arrhenius(A=(1e12, "cm^3/(mol*s)"), n=0, Ea=(0, "cal/mol"), T0=(1, "K"))
        low = Arrhenius(A=(1e18, "cm^6/(mol^2*s)"), n=0, Ea=(0, "cal/mol"), T0=(1, "K"))
        kinetics = Troe(arrheniusHigh=arrhenius, arrheniusLow=low, alpha=0.5, T3=(1, "K"), T1=(1e10, "K"),
                        efficiencies={Molecule(smiles=s): e for s, e in (efficiencies or {}).items()})
        rxn = RMGReaction(reactants=[self.species["H"], self.species["O2"]], products=[self.species["HO2"]],
                          kinetics=kinetics)
        if collider:
            rxn.specific_collider = self.species[collider]
        return rxn

    def marked(self, *reactions):
        exports._mark_duplicate_reactions(list(reactions))
        return [bool(r.duplicate) for r in reactions]

    def test_m_with_collider_efficiency_zero_is_no_duplicate(self):
        self.assertEqual(self.marked(self.reaction(efficiencies={"[Ar]": 0}), self.reaction("AR")), [False, False])

    def test_m_with_the_collider_acting_is_a_duplicate(self):
        self.assertEqual(self.marked(self.reaction(efficiencies={"O": 0}), self.reaction("AR")), [True, True])

    def test_two_colliders(self):
        self.assertEqual(self.marked(self.reaction("AR"), self.reaction("H2O")), [False, False])
        self.assertEqual(self.marked(self.reaction("AR"), self.reaction("AR")), [True, True])

    def test_two_m_reactions_are_still_duplicates(self):
        self.assertEqual(self.marked(self.reaction(), self.reaction(efficiencies={"[Ar]": 0})), [True, True])
