"""A merged library entry's rate terms go back to the reactions their CHEMKIN lines write.

AramcoMech_1.3 entry 965, CH3CHCHCHO + H <=> CH3CHCHCO + H2, is a MultiArrhenius of two terms:
CHEMKIN line 2568 (CH3CHCHCHO + H) and line 2990 (SC3H5CHO + H). SMILES.txt gave both names one
SMILES, so RMG-models took them for one species. SC3H5CHO now has its own record, so its rate
must go to its own reaction. The tests use furop1/furop2 from test_species_variants_unit.
"""
import os
import shutil
import tempfile

from django.test import SimpleTestCase, TestCase

from database import models as db
from database.scripts import chemkin_lines
from database.scripts.import_rmg_models import import_kinetics, import_thermo
from database.services import cleanup
from database.tests.test_import_rmg_species_unit import MODELS
from database.tests.test_species_variants_unit import ADJ, import_without_variants, thermo_text

LABELS = ("furop1", "furop2", "H", "CH2CO", "C2H3")
MERGED = ("furop1 + H <=> CH2CO + C2H3",
          "MultiArrhenius(arrhenius=[Arrhenius(A=(1e+13,'cm^3/(mol*s)'), n=0, Ea=(2000,'cal/mol'), T0=(1,'K')), "
          "Arrhenius(A=(2e+13,'cm^3/(mol*s)'), n=0, Ea=(1500,'cal/mol'), T0=(1,'K'))])")
LINES = ("furop1+H<=>CH2CO+C2H3   1.000E+13   0.000   2000.0",
         "furop2+H<=>CH2CO+C2H3   2.000E+13   0.000   1500.0")


def model_folder(root, name, dictionary=LABELS, entries=(MERGED,), lines=LINES, reactions_line="REACTIONS",
                 chemkin=True):
    """An RMG-models folder: thermo and kinetics libraries, SMILES.txt, import.sh and the CHEMKIN file."""
    folder = os.path.join(root, name)
    thermo_dir, kinetics_dir = (os.path.join(folder, d) for d in ("RMG-Py-thermo-library", "RMG-Py-kinetics-library"))
    os.makedirs(thermo_dir)
    os.makedirs(kinetics_dir)
    with open(os.path.join(thermo_dir, "ThermoLibrary.py"), "w") as handle:
        handle.write(thermo_text(LABELS))
    with open(os.path.join(kinetics_dir, "dictionary.txt"), "w") as handle:
        for label in dictionary:
            handle.write(f"{label}\n{ADJ[label]}\n\n")
    with open(os.path.join(kinetics_dir, "reactions.py"), "w") as handle:
        handle.write('name = "test"\nshortDesc = ""\nlongDesc = """"""\nautoGenerated=False\n')
        for index, (label, kinetics) in enumerate(entries):
            handle.write(f'entry(\n    index = {index},\n    label = "{label}",\n    degeneracy = 1.0,\n'
                         f'    duplicate = True,\n    kinetics = {kinetics},\n'
                         f'    shortDesc = """The chemkin file reaction is {label}""",\n)\n\n')
    with open(os.path.join(folder, "SMILES.txt"), "w") as handle:
        handle.write("furop1\tC=C=CC=O\nfurop2\tC=C=CC=O\nH\t[H]\nCH2CO\tC=C=O\nC2H3\t[CH]=C\n")
    if chemkin:
        with open(os.path.join(folder, "import.sh"), "w") as handle:
            handle.write("python import.py \\\n\t--species chem.inp \\\n\t--reactions chem.inp \\\n")
        with open(os.path.join(folder, "chem.inp"), "w") as handle:
            handle.write("ELEMENTS C H O END\nSPECIES furop1 furop2 H CH2CO C2H3 END\n"
                         f"{reactions_line}\n" + "\n".join(lines) + "\nEND\n")
    return os.path.join(thermo_dir, "ThermoLibrary.py"), os.path.join(kinetics_dir, "reactions.py")


class ChemkinLinesTests(SimpleTestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)

    def write(self, text):
        path = os.path.join(self.directory, "chem.inp")
        with open(path, "w") as handle:
            handle.write(text)
        return path

    def test_names_with_plus_and_counted_species(self):
        names = {"C6H5+", "OH", "H2O2", "CH3", "MECY24PD", "C2H6"}
        self.assertEqual(chemkin_lines.split_side("C6H5++2OH", names), ["C6H5+", "OH", "OH"])
        path = self.write("REACTIONS\nCH3+MECY24PD<=>C2H6+CH3 1e12 0 0\nH2O2(+M)<=>2OH(+M) 1e14 0 48000\nEND\n")
        first, second = chemkin_lines.read_reactions(path, names | {"H2O2"}, 4.184)
        # A name that starts with M is not a third body; (+M) is.
        self.assertFalse(first["third_body"])
        self.assertEqual(first["reactants"], ["CH3", "MECY24PD"])
        self.assertTrue(second["third_body"])

    def test_units_and_plog(self):
        path = self.write("REACTIONS KJOULES/MOLE\nA=B 1e10 0 10\nPLOG / 1.0 2e10 0.5 20 /\nEND\n")
        self.assertEqual(chemkin_lines.units(path), (1000.0, False))
        (line,) = chemkin_lines.read_reactions(path, {"A", "B"}, 1000.0)
        self.assertEqual((line["Ea"], line["plog"]), (10000.0, (2e10, 0.5, 20000.0)))

    def test_undeclared_units_come_from_the_library(self):
        # MatheuCH4: no unit on the REACTIONS line, Ea in kcal/mol, as RMG-models wrote the library.
        path = self.write("REACTIONS\nA=B 1e10 0 5.0\nEND\n")
        library = os.path.join(self.directory, "reactions.py")
        with open(library, "w") as handle:
            handle.write("kinetics = Arrhenius(A=(1e10,'s^-1'), n=0, Ea=(5,'kcal/mol'), T0=(1,'K'))\n")
        self.assertEqual(chemkin_lines.units(path, library), (4184.0, False))
        self.assertEqual(chemkin_lines.units(path), (4.184, False))


class MergedRatesTests(TestCase):
    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.directory)
        self.model = db.KineticModel.objects.create(model_name="m")

    def import_model(self, **folder):
        thermo_path, kinetics_path = model_folder(self.directory, self.model.model_name, **folder)
        self.assertEqual(import_thermo(thermo_path, self.model, MODELS)["failed"], 0)
        counts = import_kinetics(kinetics_path, self.model, MODELS)
        self.assertEqual((counts["failed"], counts["rejected"]), (0, 0))
        return counts

    def record(self, name):
        return db.Species.objects.get(speciesname__kinetic_model=self.model, speciesname__name=name)

    def link(self, equation):
        return db.KineticsComment.objects.get(kinetic_model=self.model,
                                              comment=f"The chemkin file reaction is {equation}")

    def assert_split(self):
        one, two = self.link("furop1 + H <=> CH2CO + C2H3"), self.link("furop2 + H <=> CH2CO + C2H3")
        self.assertEqual((one.kinetics.raw_data["type"], one.kinetics.raw_data["a"]), ("arrhenius", 1e13))
        self.assertEqual((two.kinetics.raw_data["type"], two.kinetics.raw_data["a"]), ("arrhenius", 2e13))
        species = lambda link: set(link.kinetics.reaction.stoichiometry_set.values_list("species_id", flat=True))
        self.assertIn(self.record("furop1").pk, species(one))
        self.assertIn(self.record("furop2").pk, species(two))
        self.assertNotIn(self.record("furop1").pk, species(two))
        self.assertTrue(two.reversible)

    def test_each_rate_goes_to_its_names_reaction(self):
        counts = self.import_model()
        self.assertEqual(counts["moved_terms"], 1)
        self.assert_split()
        self.assertEqual(db.KineticsComment.objects.filter(kinetic_model=self.model).count(), 2)

    def test_a_name_the_dictionary_leaves_out(self):
        # MatheuCH4: the kinetics dictionary keeps one label per molecule (no furop2).
        self.import_model(dictionary=("furop1", "H", "CH2CO", "C2H3"))
        self.assert_split()

    def test_a_first_name_the_dictionary_leaves_out(self):
        # Atef: the dictionary kept C6H13COC2H3, the later name, and left out NC6H13COC2H3, the first.
        entry = ("furop2 + H <=> CH2CO + C2H3",
                 "MultiArrhenius(arrhenius=[Arrhenius(A=(2e+13,'cm^3/(mol*s)'), n=0, Ea=(1500,'cal/mol'), T0=(1,'K')), "
                 "Arrhenius(A=(1e+13,'cm^3/(mol*s)'), n=0, Ea=(2000,'cal/mol'), T0=(1,'K'))])")
        self.import_model(dictionary=("furop2", "H", "CH2CO", "C2H3"), entries=(entry,))
        self.assert_split()

    def test_undeclared_kcal_units(self):
        lines = ("furop1+H<=>CH2CO+C2H3   1.000E+13   0.000   2.0",
                 "furop2+H<=>CH2CO+C2H3   2.000E+13   0.000   1.5")
        merged = (MERGED[0], MERGED[1].replace("Ea=(2000,'cal/mol')", "Ea=(2,'kcal/mol')")
                  .replace("Ea=(1500,'cal/mol')", "Ea=(1.5,'kcal/mol')"))
        self.import_model(lines=lines, entries=(merged,))
        self.assert_split()

    def test_identical_rates_keep_one_on_each_name(self):
        same = MERGED[1].replace("A=(2e+13", "A=(1e+13").replace("Ea=(1500", "Ea=(2000")
        lines = (LINES[0], LINES[0].replace("furop1", "furop2"))
        self.import_model(entries=((MERGED[0], same),), lines=lines)
        one, two = self.link("furop1 + H <=> CH2CO + C2H3"), self.link("furop2 + H <=> CH2CO + C2H3")
        self.assertEqual((one.kinetics.raw_data["a"], two.kinetics.raw_data["a"]), (1e13, 1e13))
        self.assertNotEqual(one.kinetics.reaction_id, two.kinetics.reaction_id)

    def test_without_the_chemkin_file_the_entry_stays_whole(self):
        counts = self.import_model(chemkin=False)
        self.assertNotIn("moved_terms", counts)
        self.assertEqual(self.link("furop1 + H <=> CH2CO + C2H3").kinetics.raw_data["type"], "multi_arrhenius")

    def test_an_unmatched_term_stays_on_the_entry(self):
        self.import_model(lines=(LINES[0],))
        self.assertEqual(self.link("furop1 + H <=> CH2CO + C2H3").kinetics.raw_data["type"], "multi_arrhenius")

    def test_without_variants_the_entry_stays_whole(self):
        thermo_path, kinetics_path = model_folder(self.directory, "m")
        counts = import_without_variants(thermo_path, kinetics_path, self.model)
        self.assertNotIn("moved_terms", counts)
        self.assertEqual(self.link("furop1 + H <=> CH2CO + C2H3").kinetics.raw_data["type"], "multi_arrhenius")

    def test_importing_again_adds_nothing(self):
        self.import_model()
        before = [table.objects.count() for table in (db.Reaction, db.Kinetics, db.KineticsComment)]
        thermo_path = os.path.join(self.directory, "m", "RMG-Py-thermo-library", "ThermoLibrary.py")
        kinetics_path = os.path.join(self.directory, "m", "RMG-Py-kinetics-library", "reactions.py")
        import_thermo(thermo_path, self.model, MODELS)
        import_kinetics(kinetics_path, self.model, MODELS)
        self.assertEqual([table.objects.count() for table in (db.Reaction, db.Kinetics, db.KineticsComment)], before)

    def test_rebuild_moves_the_rate_to_its_name(self):
        thermo_path, kinetics_path = model_folder(self.directory, "m")
        import_without_variants(thermo_path, kinetics_path, self.model)
        merged = self.link("furop1 + H <=> CH2CO + C2H3").kinetics
        self.assertEqual(merged.raw_data["type"], "multi_arrhenius")
        result = cleanup.rebuild_model_links(self.model, thermo_path, kinetics_path)
        self.assertEqual(result["kinetics_import"]["moved_terms"], 1)
        self.assertEqual(result["kinetics_links"]["after"], 2)
        self.assert_split()
        self.assertFalse(db.KineticsComment.objects.filter(kinetics=merged, kinetic_model=self.model).exists())
        self.assertEqual(cleanup.integrity_report()["kinetics_links_not_their_equation"], 0)
